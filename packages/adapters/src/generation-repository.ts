import { and, asc, desc, eq, inArray } from 'drizzle-orm';
import type {
  ContentVersionId,
  GenerationRepository,
  GenerationStatus,
  GlossaryEntry,
  LessonId,
  LessonPartContent,
  LessonSourcePart,
  LessonSources,
  NewLessonFeed,
  OwnedLesson,
  SubtitleCue,
  SubtitleTrack,
  UserId,
} from '@study-feed/core';
import { glossaryKey, parseContentHash, parseId } from '@study-feed/core';
import {
  chapters,
  contentVersions,
  entitlements,
  glossaryTerms,
  lessonFeeds,
  lessonParts,
  lessons,
  subjects,
  subtitleTracks,
} from '@study-feed/db';
import type { Database, DatabaseTransaction } from './database.js';
import { withUserRls } from './database.js';

/**
 * Persistenza della generazione su Postgres (porta `GenerationRepository` del
 * core, ADR 0013).
 *
 * Le **letture** passano dalla RLS dello studente ({@link withUserRls}): la
 * query non filtra per utente, lo fa il database, quindi un errore qui non può
 * mostrare lezioni, sottotitoli o feed di altri. Le **scritture** (feed,
 * glossario, stato delle versioni) usano la connessione del server, dopo che
 * il caso d'uso ha verificato fonti e permessi.
 */
export class DrizzleGenerationRepository implements GenerationRepository {
  /**
   * @param db - Database con permessi di scrittura (solo lato server).
   */
  constructor(private readonly db: Database) {}

  /** {@inheritDoc GenerationRepository.listOwnedLessons} */
  async listOwnedLessons(userId: UserId): Promise<OwnedLesson[]> {
    const rows = await withUserRls(this.db, userId, (tx) =>
      latestVersions(tx).orderBy(
        asc(subjects.title),
        asc(chapters.position),
        asc(lessons.position),
        asc(lessons.id),
        asc(lessonParts.position),
      ),
    );
    const byLesson = new Map<string, OwnedLesson & { sources: OwnedLesson['sources'][number][] }>();
    for (const row of rows) {
      let lesson = byLesson.get(row.lessonId);
      if (!lesson) {
        lesson = {
          lessonId: parseId(row.lessonId, 'LessonId'),
          lessonTitle: row.lessonTitle,
          chapterTitle: row.chapterTitle,
          subjectTitle: row.subjectTitle,
          sources: [],
        };
        byLesson.set(row.lessonId, lesson);
      }
      lesson.sources.push({
        lessonPartId: parseId(row.lessonPartId, 'LessonPartId'),
        contentHash: parseContentHash(row.contentHash),
      });
    }
    return [...byLesson.values()];
  }

  /** {@inheritDoc GenerationRepository.listVisibleFeeds} */
  async listVisibleFeeds(userId: UserId) {
    const rows = await withUserRls(this.db, userId, (tx) =>
      tx
        .select({ lessonId: lessonFeeds.lessonId, sourcesHash: lessonFeeds.sourcesHash })
        .from(lessonFeeds),
    );
    return rows.map((row) => ({
      lessonId: parseId(row.lessonId, 'LessonId'),
      sourcesHash: parseContentHash(row.sourcesHash),
    }));
  }

  /** {@inheritDoc GenerationRepository.loadLessonSources} */
  async loadLessonSources(userId: UserId, lessonId: LessonId): Promise<LessonSources | null> {
    return withUserRls(this.db, userId, async (tx) => {
      const parts = await latestVersions(tx)
        .where(eq(lessons.id, lessonId))
        .orderBy(asc(lessonParts.position), asc(lessonParts.id));
      const first = parts[0];
      if (!first) return null;

      const partIds = parts.map((part) => part.lessonPartId);
      // Visibili solo le tracce a cui lo studente ha accesso (RLS); per ogni
      // lingua si tiene la più recente.
      const tracks = await tx
        .select({
          lessonPartId: subtitleTracks.lessonPartId,
          language: subtitleTracks.language,
          autoGenerated: subtitleTracks.autoGenerated,
          cues: subtitleTracks.cues,
        })
        .from(subtitleTracks)
        .where(inArray(subtitleTracks.lessonPartId, partIds))
        .orderBy(desc(subtitleTracks.firstSeenAt));
      const tracksByPart = new Map<string, SubtitleTrack[]>();
      for (const track of tracks) {
        const list = tracksByPart.get(track.lessonPartId) ?? [];
        if (!list.some((existing) => existing.language === track.language)) {
          list.push({
            language: track.language,
            autoGenerated: track.autoGenerated,
            cues: track.cues as SubtitleCue[],
          });
        }
        tracksByPart.set(track.lessonPartId, list);
      }

      const glossary = await tx
        .select({
          term: glossaryTerms.term,
          translation: glossaryTerms.translation,
          definition: glossaryTerms.definition,
        })
        .from(glossaryTerms)
        .where(eq(glossaryTerms.subjectId, first.subjectId))
        .orderBy(asc(glossaryTerms.termKey));

      return {
        lessonId: parseId(first.lessonId, 'LessonId'),
        lessonTitle: first.lessonTitle,
        chapterTitle: first.chapterTitle,
        subjectId: first.subjectId,
        subjectTitle: first.subjectTitle,
        parts: parts.map((part): LessonSourcePart => ({
          lessonPartId: parseId(part.lessonPartId, 'LessonPartId'),
          contentVersionId: parseId(part.contentVersionId, 'ContentVersionId'),
          contentHash: parseContentHash(part.contentHash),
          title: part.partTitle,
          kind: part.kind,
          position: part.position,
          content: part.content as LessonPartContent,
          generationStatus: part.generationStatus,
          subtitles: tracksByPart.get(part.lessonPartId) ?? [],
        })),
        glossary: glossary.map((entry): GlossaryEntry => ({
          term: entry.term,
          translation: entry.translation,
          definition: entry.definition as GlossaryEntry['definition'],
        })),
      };
    });
  }

  /** {@inheritDoc GenerationRepository.setGenerationStatus} */
  async setGenerationStatus(
    versionIds: readonly ContentVersionId[],
    to: GenerationStatus,
    from: readonly GenerationStatus[],
  ): Promise<void> {
    await updateStatus(this.db, versionIds, to, from);
  }

  /** {@inheritDoc GenerationRepository.saveLessonFeed} */
  async saveLessonFeed(feed: NewLessonFeed): Promise<{ feedId: string; created: boolean }> {
    return this.db.transaction(async (tx) => {
      const { document } = feed;
      const [inserted] = await tx
        .insert(lessonFeeds)
        .values({
          lessonId: document.lessonId,
          sourcesHash: document.sourcesHash,
          promptVersion: document.promptVersion,
          feed: document,
          sourceVersionIds: [...feed.sourceVersionIds],
          generatedBy: feed.generatedBy,
          generatedAt: new Date(document.generatedAt),
        })
        // Vale il primo feed per le stesse fonti (ADR 0007): un secondo
        // salvataggio non sovrascrive ciò che altri stanno già studiando.
        .onConflictDoNothing({ target: [lessonFeeds.lessonId, lessonFeeds.sourcesHash] })
        .returning({ id: lessonFeeds.id });

      let feedId = inserted?.id;
      if (feedId === undefined) {
        const [existing] = await tx
          .select({ id: lessonFeeds.id })
          .from(lessonFeeds)
          .where(
            and(
              eq(lessonFeeds.lessonId, document.lessonId),
              eq(lessonFeeds.sourcesHash, document.sourcesHash),
            ),
          );
        if (!existing) throw new Error('Feed non trovato dopo il conflitto');
        feedId = existing.id;
      }

      if (feed.glossary.length > 0) {
        await tx
          .insert(glossaryTerms)
          .values(
            feed.glossary.map((entry) => ({
              subjectId: feed.subjectId,
              term: entry.term,
              termKey: glossaryKey(entry.term),
              translation: entry.translation,
              definition: entry.definition,
            })),
          )
          // A parità di termine resta la prima voce: il glossario cresce, non cambia sotto i piedi.
          .onConflictDoNothing({ target: [glossaryTerms.subjectId, glossaryTerms.termKey] });
      }

      await updateStatus(tx, feed.sourceVersionIds, 'ready', feed.readyFrom);
      return { feedId, created: inserted !== undefined };
    });
  }
}

/**
 * Per ogni parte posseduta dallo studente, la sua versione più recente, con
 * parte e lezione. Va eseguita dentro {@link withUserRls}.
 */
function latestVersions(tx: DatabaseTransaction) {
  const latest = tx
    .selectDistinctOn([entitlements.lessonPartId], {
      lessonPartId: entitlements.lessonPartId,
      contentVersionId: contentVersions.id,
      contentHash: contentVersions.contentHash,
      content: contentVersions.content,
      generationStatus: contentVersions.generationStatus,
    })
    .from(entitlements)
    .innerJoin(contentVersions, eq(contentVersions.id, entitlements.contentVersionId))
    .orderBy(entitlements.lessonPartId, desc(contentVersions.firstSeenAt))
    .as('latest');
  return tx
    .select({
      lessonPartId: latest.lessonPartId,
      contentVersionId: latest.contentVersionId,
      contentHash: latest.contentHash,
      content: latest.content,
      generationStatus: latest.generationStatus,
      partTitle: lessonParts.title,
      kind: lessonParts.kind,
      position: lessonParts.position,
      lessonId: lessons.id,
      lessonTitle: lessons.title,
      chapterTitle: chapters.title,
      subjectId: subjects.id,
      subjectTitle: subjects.title,
    })
    .from(latest)
    .innerJoin(lessonParts, eq(lessonParts.id, latest.lessonPartId))
    .innerJoin(lessons, eq(lessons.id, lessonParts.lessonId))
    .innerJoin(chapters, eq(chapters.id, lessons.chapterId))
    .innerJoin(subjects, eq(subjects.id, chapters.subjectId))
    .$dynamic();
}

async function updateStatus(
  db: Database | DatabaseTransaction,
  versionIds: readonly string[],
  to: GenerationStatus,
  from: readonly GenerationStatus[],
): Promise<void> {
  if (versionIds.length === 0 || from.length === 0) return;
  await db
    .update(contentVersions)
    .set({ generationStatus: to, generationUpdatedAt: new Date() })
    .where(
      and(
        inArray(contentVersions.id, [...versionIds]),
        inArray(contentVersions.generationStatus, [...from]),
      ),
    );
}
