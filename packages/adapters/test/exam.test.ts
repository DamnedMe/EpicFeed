import type { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type {
  ExamExercise,
  ExamPackDraft,
  LessonFeedDraft,
  LessonId,
  LessonImport,
  UserId,
} from '@study-feed/core';
import {
  ImportLesson,
  ListLessonsForExam,
  ListSubjectsForExam,
  PossessionProofVerifier,
  ReadLessonForExam,
  ReadLessonForGeneration,
  SaveExamBank,
  SaveExamPack,
  SaveLessonFeed,
} from '@study-feed/core';
import { DrizzleCatalogRepository } from '../src/catalog-repository.js';
import type { Database } from '../src/database.js';
import { DrizzleExamPackRepository } from '../src/exam-repository.js';
import { DrizzleGenerationRepository } from '../src/generation-repository.js';
import { anna, bruno, setup } from './setup.js';

let pg: PGlite;
let db: Database;
let exams: DrizzleExamPackRepository;
let binaryTrees: LessonId;
let heaps: LessonId;
let feedId: string;
const clock = { now: () => new Date('2026-11-24T10:00:00Z') };
const bi = (it: string, en: string) => ({ it, en });

const lines = [
  ...Array.from({ length: 8 }, (_, i) => `osservazione generica numero ${i} sulle liste`),
  'un albero AVL è un albero binario di ricerca che si ribilancia da solo',
  'il fattore di bilanciamento di ogni nodo resta al massimo uno',
  'dopo un inserimento serve una rotazione per ribilanciare',
  ...Array.from({ length: 8 }, (_, i) => `osservazione generica numero ${i + 8} sulle code`),
];

function lesson(epicodeId: string, title: string, position: number): LessonImport {
  return {
    path: {
      studyProgram: { epicodeId: '5', title: 'EIT' },
      edition: { label: '2024/25' },
      subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
      chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
      lesson: { epicodeId, title, position },
    },
    parts: [
      {
        epicodeId: `${epicodeId}1`,
        title: `${title} video`,
        position: 0,
        kind: 'video',
        videoId: '1034168708',
        content: { kind: 'video', summaries: { it: `Riassunto ${title}`, en: 'Summary' } },
        subtitles: [
          {
            language: 'it',
            autoGenerated: false,
            cues: lines.map((text, i) => ({ startMs: i * 5000, endMs: i * 5000 + 4000, text })),
          },
        ],
      },
      {
        epicodeId: `${epicodeId}2`,
        title: `${title} - Summary`,
        position: 1,
        kind: 'reading',
        content: { kind: 'reading', markdown: `# ${title}` },
      },
    ],
  };
}

function draft(readingPart: string): LessonFeedDraft {
  const concept = 'avl-tree' as LessonFeedDraft['concepts'][number]['key'];
  const question = (id: string): LessonFeedDraft['quiz'][number] => ({
    id,
    kind: 'true_false',
    question: bi('Un AVL è un BST?', 'Is an AVL a BST?'),
    answer: true,
    explanation: bi('Sì.', 'Yes.'),
    conceptKey: concept,
    difficulty: 1,
  });
  const card = (id: string): LessonFeedDraft['cards'][number] => ({
    id,
    kind: 'concept',
    title: bi('Albero AVL', 'AVL tree'),
    keyPoint: bi(
      'Un albero binario di ricerca che si ribilancia da solo.',
      'A self-balancing BST.',
    ),
    body: bi(
      'Il fattore di bilanciamento resta al massimo uno grazie a una rotazione dopo ogni inserimento.',
      'The balance factor stays at most one thanks to a rotation after each insertion.',
    ),
    terms: ['AVL tree', 'balance factor'],
    conceptKeys: [concept],
    sourcePartId: readingPart as LessonFeedDraft['cards'][number]['sourcePartId'],
    origin: 'reading',
  });
  return {
    cards: [card('a'), card('b'), card('c')],
    quiz: [question('q1'), question('q2')],
    concepts: [{ key: concept, name: bi('Albero AVL', 'AVL tree'), description: bi('BST', 'BST') }],
    glossary: [],
  };
}

const concept = 'avl-tree' as ExamPackDraft['questions'][number]['conceptKey'];

const pack: ExamPackDraft = {
  questions: Array.from({ length: 10 }, (_, i) => ({
    id: `q-${i}`,
    question: `Which rotation fixes imbalance case ${i}?`,
    options: ['Left', 'Right', 'Left-right', 'Right-left'],
    correctIndex: i % 4,
    explanation: 'It restores the balance factor.',
    conceptKey: concept,
    difficulty: 2,
  })),
  openQuestions: [
    {
      id: 'explain-avl',
      kind: 'explain',
      prompt: 'Explain why an AVL tree keeps O(log n) height.',
      hints: [bi('Pensa al fattore di bilanciamento.', 'Think about the balance factor.')],
      modelAnswer: 'Rotations keep every balance factor within one.',
      rubric: [
        { criterion: 'Defines the balance factor', points: 2 },
        { criterion: 'Mentions rotations', points: 2 },
        { criterion: 'Derives the height bound', points: 1 },
      ],
      conceptKeys: [concept],
      followUp: 'What changes for a red-black tree?',
    },
  ],
};

beforeAll(async () => {
  ({ pg, db } = await setup());
  exams = new DrizzleExamPackRepository(db);
  const generation = new DrizzleGenerationRepository(db);
  const importLesson = new ImportLesson({
    catalog: new DrizzleCatalogRepository(db),
    verifier: new PossessionProofVerifier(clock),
    clock,
  });
  binaryTrees = (await importLesson.execute(anna as UserId, lesson('66863', 'Binary trees', 1)))
    .lessonId;
  heaps = (await importLesson.execute(anna as UserId, lesson('66870', 'Heaps', 2))).lessonId;
  for (const lessonId of [heaps, binaryTrees]) {
    const read = await new ReadLessonForGeneration(generation).execute(anna as UserId, lessonId);
    const saved = await new SaveLessonFeed({ repository: generation, clock }).execute(
      anna as UserId,
      {
        lessonId,
        sourcesHash: read.sourcesHash,
        promptVersion: '2026-11-21.2',
        feed: draft(read.parts[1]?.lessonPartId ?? ''),
      },
    );
    if (lessonId === binaryTrees) feedId = saved.feedId;
  }
});

afterAll(async () => {
  await pg.close();
});

describe('DrizzleExamPackRepository', () => {
  it('elenca i feed correnti in ordine di studio, solo a chi li vede', async () => {
    const list = new ListLessonsForExam(exams);
    const result = await list.execute(anna as UserId, 10);
    expect(result.lessons.map((lesson) => lesson.lessonTitle)).toEqual(['Binary trees', 'Heaps']);
    expect(result.totals).toEqual({ lessons: 2, ready: 0, toGenerate: 2 });
    expect((await list.execute(bruno as UserId, 10)).totals.lessons).toBe(0);
  });

  it('legge il feed della lezione e salva il pacchetto una volta sola', async () => {
    const material = await new ReadLessonForExam(exams).execute(anna as UserId, binaryTrees);
    expect(material.feedId).toBe(feedId);
    expect(material.concepts).toEqual([{ key: 'avl-tree', name: 'AVL tree', description: 'BST' }]);
    expect(material.feedQuestions).toEqual(['Is an AVL a BST?', 'Is an AVL a BST?']);

    const save = new SaveExamPack({ repository: exams, clock });
    const input = { lessonId: binaryTrees, feedId, promptVersion: '2026-11-24.1', pack };
    const first = await save.execute(anna as UserId, input);
    expect(first).toMatchObject({ created: true, questions: 10, openQuestions: 1 });
    const second = await save.execute(anna as UserId, input);
    expect(second).toEqual({ ...first, created: false });

    const stored = await pg.query<{ pack: { feedId: string; questions: unknown[] } }>(
      'select pack from lesson_exam_packs',
    );
    expect(stored.rows[0]?.pack.feedId).toBe(feedId);
    expect(stored.rows[0]?.pack.questions).toHaveLength(10);

    const after = await new ListLessonsForExam(exams).execute(anna as UserId, 10);
    expect(after.totals).toEqual({ lessons: 2, ready: 1, toGenerate: 1 });
    expect((await exams.loadCurrentFeed(anna as UserId, binaryTrees))?.hasExamPack).toBe(true);
  });

  it('non mostra il feed a chi non ha importato la lezione', async () => {
    expect(await exams.loadCurrentFeed(bruno as UserId, binaryTrees)).toBeNull();
  });

  it("salva la banca d'esame della materia, privata di chi la genera", async () => {
    const list = new ListSubjectsForExam(exams);
    const [subject] = await list.execute(anna as UserId);
    expect(subject?.concepts).toEqual([{ key: 'avl-tree', name: 'AVL tree', description: 'BST' }]);
    expect(subject?.hasBank).toBe(false);
    expect(await list.execute(bruno as UserId)).toEqual([]);

    const base = pack.openQuestions[0];
    if (!base || !subject) throw new Error('fixture');
    const exercise = (id: string, extra: Partial<ExamExercise> = {}): ExamExercise => ({
      ...base,
      id,
      title: id,
      origin: 'official',
      page: 3,
      ...extra,
    });
    const input = {
      subjectId: subject.subjectId,
      promptVersion: '2026-11-24.1',
      bank: {
        exercises: [
          exercise('avl'),
          exercise('avl-a', { origin: 'variant', variantOf: 'avl' }),
          exercise('avl-b', { origin: 'variant', variantOf: 'avl' }),
        ],
      },
    };
    const save = new SaveExamBank({ repository: exams, clock });
    const first = await save.execute(anna as UserId, input);
    expect(first).toMatchObject({ created: true, officials: 1, variants: 2 });
    expect(await save.execute(anna as UserId, input)).toEqual({ ...first, created: false });
    expect((await list.execute(anna as UserId))[0]?.hasBank).toBe(true);
    await expect(save.execute(bruno as UserId, input)).rejects.toMatchObject({ code: 'NOT_FOUND' });
  });
});
