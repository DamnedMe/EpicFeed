import { describe, expect, it } from 'vitest';
import type { SubtitleTrack } from './subtitles.js';
import {
  MAX_SUBTITLE_CUES,
  computeSubtitleTrackHash,
  normalizeSubtitleTrack,
} from './subtitles.js';

const track: SubtitleTrack = {
  language: ' IT ',
  autoGenerated: false,
  cues: [
    { startMs: 4000, endMs: 6000, text: 'seconda\nriga' },
    { startMs: 0, endMs: 3000, text: 'prima riga ' },
    { startMs: 7000, endMs: 8000, text: '   ' },
  ],
};

describe('normalizeSubtitleTrack', () => {
  it('ordina le righe, unisce gli a capo, scarta le righe vuote', () => {
    expect(normalizeSubtitleTrack(track)).toEqual({
      language: 'it',
      autoGenerated: false,
      cues: [
        { startMs: 0, endMs: 3000, text: 'prima riga' },
        { startMs: 4000, endMs: 6000, text: 'seconda riga' },
      ],
    });
  });

  it('a parità di inizio ordina per fine e accetta le lingue automatiche di Vimeo', () => {
    const result = normalizeSubtitleTrack({
      language: 'en-x-autogen',
      autoGenerated: true,
      cues: [
        { startMs: 0, endMs: 2000, text: 'b' },
        { startMs: 0, endMs: 1000, text: 'a' },
      ],
    });
    expect(result.cues.map((cue) => cue.text)).toEqual(['a', 'b']);
    expect(result.language).toBe('en-x-autogen');
  });

  it.each<[string, SubtitleTrack]>([
    ['lingua non valida', { ...track, language: 'italiano!' }],
    ['traccia vuota', { ...track, cues: [{ startMs: 0, endMs: 1, text: ' ' }] }],
    ['tempi negativi', { ...track, cues: [{ startMs: -1, endMs: 5, text: 'x' }] }],
    ['fine prima di inizio', { ...track, cues: [{ startMs: 9, endMs: 5, text: 'x' }] }],
    ['tempi decimali', { ...track, cues: [{ startMs: 0.5, endMs: 5, text: 'x' }] }],
    [
      'troppe righe',
      {
        ...track,
        cues: Array.from({ length: MAX_SUBTITLE_CUES + 1 }, (_, i) => ({
          startMs: i,
          endMs: i,
          text: 'x',
        })),
      },
    ],
  ])('rifiuta: %s', (_label, input) => {
    expect(() => normalizeSubtitleTrack(input)).toThrow(
      expect.objectContaining({ code: 'INVALID_CONTENT' }),
    );
  });
});

describe('computeSubtitleTrackHash', () => {
  it('è stabile rispetto a spazi e ordine, e cambia se cambia il testo', async () => {
    const same: SubtitleTrack = { ...track, cues: [...track.cues].reverse(), language: 'it' };
    expect(await computeSubtitleTrackHash(same)).toBe(await computeSubtitleTrackHash(track));
    const changed: SubtitleTrack = {
      ...track,
      cues: [{ startMs: 0, endMs: 3000, text: 'prima riga corretta' }],
    };
    expect(await computeSubtitleTrackHash(changed)).not.toBe(await computeSubtitleTrackHash(track));
  });
});
