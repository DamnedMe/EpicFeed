import * as z from 'zod';
import { MAX_TEXT_LENGTH } from '../domain/content.js';
import { MAX_SUBTITLE_CUES } from '../domain/subtitles.js';

/**
 * Forma dei contenuti del catalogo ai confini (estensione → API, API → server
 * MCP): nodi, contenuto di una parte e sottotitoli. Solo la forma: le regole
 * stanno nel dominio.
 */

/** Id di un elemento Directus: interi o UUID, solo caratteri sicuri. */
export const epicodeIdSchema = z.string().regex(/^[A-Za-z0-9-]{1,64}$/, 'Id Epicode non valido');

/** Titolo di un nodo del catalogo. */
export const catalogTitleSchema = z.string().min(1).max(300);
/** Posizione di un nodo tra i fratelli. */
export const catalogPositionSchema = z.number().int().min(0).max(100_000);
const textSchema = z.string().max(MAX_TEXT_LENGTH);

/** Nodo del catalogo come arriva dal portale. */
export const catalogNodeSchema = z.strictObject({
  epicodeId: epicodeIdSchema,
  title: catalogTitleSchema,
  position: catalogPositionSchema,
});

/** Riga dei sottotitoli, con tempi in millisecondi interi. */
export const subtitleCueSchema = z.strictObject({
  startMs: z.number().int().min(0),
  endMs: z.number().int().min(0),
  text: z.string().max(2_000),
});

/** Traccia di sottotitoli di una parte video (separata dalla versione, ADR 0006). */
export const subtitleTrackSchema = z.strictObject({
  language: z.string().regex(/^[A-Za-z]{2,3}(-[A-Za-z0-9]{1,8}){0,3}$/, 'Lingua non valida'),
  autoGenerated: z.boolean(),
  cues: z.array(subtitleCueSchema).min(1).max(MAX_SUBTITLE_CUES),
});

const videoContentSchema = z.strictObject({
  kind: z.literal('video'),
  summaries: z.strictObject({ it: textSchema.optional(), en: textSchema.optional() }),
});

const readingContentSchema = z.strictObject({
  kind: z.literal('reading'),
  markdown: textSchema,
});

/** Contenuto di una parte: video (riassunti e sottotitoli) o testo markdown. */
export const lessonPartContentSchema = z.discriminatedUnion('kind', [
  videoContentSchema,
  readingContentSchema,
]);
