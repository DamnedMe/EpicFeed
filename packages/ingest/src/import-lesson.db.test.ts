import type { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { LessonImport } from './domain/import.js';
import type { UserId } from '@epicfeed/shared';
import { PossessionProofVerifier } from '@epicfeed/catalog';
import { DrizzleCatalogRepository, MyLessonsQuery } from '@epicfeed/catalog/infrastructure';
import { ImportLesson } from './application/import-lesson.js';
import { setupTestDatabase as setup, TEST_USERS } from '@epicfeed/db/testing';
import type { Database } from '@epicfeed/db';

const { anna, bruno } = TEST_USERS;

let pg: PGlite;
let db: Database;
let importLesson: ImportLesson;
const clock = { now: () => new Date('2026-11-15T12:00:00Z') };

beforeAll(async () => {
  ({ pg, db } = await setup());
  importLesson = new ImportLesson({
    catalog: new DrizzleCatalogRepository(db),
    verifier: new PossessionProofVerifier(clock),
    clock,
  });
});

afterAll(async () => {
  await pg.close();
});

function binaryTrees(summary: string, subtitle = 'Un albero binario'): LessonImport {
  return {
    path: {
      studyProgram: { epicodeId: '5', title: 'EIT' },
      edition: { label: '2024/25' },
      subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
      chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
      lesson: { epicodeId: '66863', title: 'Binary trees', position: 1 },
    },
    parts: [
      {
        epicodeId: '66864',
        title: 'Properties of binary trees',
        position: 0,
        kind: 'video',
        videoId: '1034168708',
        content: { kind: 'video', summaries: { it: summary } },
        subtitles: [
          {
            language: 'it',
            autoGenerated: false,
            cues: [{ startMs: 0, endMs: 900, text: subtitle }],
          },
        ],
      },
      {
        epicodeId: '103064',
        title: 'Binary trees - Summary',
        position: 6,
        kind: 'reading',
        content: { kind: 'reading', markdown: '# Binary trees - Summary' },
      },
    ],
  };
}

const count = async (table: string) =>
  (await pg.query<{ n: number }>(`select count(*)::int as n from ${table}`)).rows[0]?.n;

describe('DrizzleCatalogRepository con ImportLesson', () => {
  it('importa la lezione e la deduplica ai reimport, anche di altri studenti', async () => {
    const first = await importLesson.execute(anna as UserId, binaryTrees('Riassunto'));
    expect(first.parts.map((p) => p.newVersion)).toEqual([true, true]);

    const again = await importLesson.execute(anna as UserId, binaryTrees('Riassunto  \r\n'));
    expect(again.lessonId).toBe(first.lessonId);
    expect(again.parts.some((p) => p.newVersion || p.newEntitlement)).toBe(false);

    const other = await importLesson.execute(bruno as UserId, binaryTrees('Riassunto'));
    expect(other.parts.map((p) => p.newEntitlement)).toEqual([true, true]);
    expect(other.parts[0]?.subtitles[0]?.newTrack).toBe(false);

    expect(await count('lessons')).toBe(1);
    expect(await count('content_versions')).toBe(2);
    expect(await count('subtitle_tracks')).toBe(1);
    expect(await count('entitlements')).toBe(4);
    expect(await count('subtitle_access')).toBe(2);
  });

  it('un riassunto cambiato crea una nuova versione, un sottotitolo corretto solo una nuova traccia', async () => {
    const changed = await importLesson.execute(anna as UserId, binaryTrees('Riassunto v2'));
    expect(changed.parts[0]?.newVersion).toBe(true);
    const fixed = await importLesson.execute(
      anna as UserId,
      binaryTrees('Riassunto v2', 'Un albero binario corretto'),
    );
    expect(fixed.parts[0]?.newVersion).toBe(false);
    expect(fixed.parts[0]?.subtitles[0]?.newTrack).toBe(true);
    const row = (
      await pg.query<{ video_id: string; title: string }>(
        `select video_id, title from lesson_parts where epicode_id = '66864'`,
      )
    ).rows[0];
    expect(row).toEqual({ video_id: '1034168708', title: 'Properties of binary trees' });
  });

  it('aggiorna il titolo se Epicode rinomina la lezione', async () => {
    const renamed = binaryTrees('Riassunto v2');
    await importLesson.execute(anna as UserId, {
      ...renamed,
      path: { ...renamed.path, lesson: { ...renamed.path.lesson, title: 'Alberi binari' } },
    });
    const titles = (await pg.query<{ title: string }>('select title from lessons')).rows;
    expect(titles).toEqual([{ title: 'Alberi binari' }]);
  });

  it('una transazione fallita non lascia nulla a metà', async () => {
    const before = await count('lesson_parts');
    const broken = binaryTrees('Riassunto v3');
    // L'id del video su una parte di testo viola un vincolo del database:
    // simula un guasto a metà transazione aggirando la validazione del core.
    const repo = new DrizzleCatalogRepository(db);
    await expect(
      repo.transaction(async (tx) => {
        const lessonId = await tx.upsertLessonPath({
          ...broken.path,
          lesson: { epicodeId: '99999', title: 'Nuova', position: 9 },
        });
        await tx.upsertLessonPart(lessonId, {
          epicodeId: '1',
          title: 'Testo',
          position: 0,
          kind: 'reading',
          videoId: '123',
        });
      }),
    ).rejects.toThrow();
    expect(await count('lesson_parts')).toBe(before);
    expect(await count(`lessons where epicode_id = '99999'`)).toBe(0);
  });
});

describe('MyLessonsQuery', () => {
  it('mostra a ciascuno solo le proprie lezioni, con lo stato delle parti', async () => {
    const query = new MyLessonsQuery(db);
    const mine = await query.list(anna);
    expect(mine).toHaveLength(1);
    expect(mine[0]).toMatchObject({
      lessonTitle: 'Alberi binari',
      chapterTitle: '3. Trees',
      subjectTitle: 'Data Structures and Algorithms',
      editionLabel: '2024/25',
      partCount: 2,
      partsWithSubtitles: 1,
      status: { pending: 2, generating: 0, ready: 0, failed: 0 },
    });
    expect(mine[0]?.lastImportedAt).toBeInstanceOf(Date);

    const nobody = '0c0c0c0c-0000-4000-8000-00000000000c';
    await pg.exec(`insert into auth.users (id) values ('${nobody}')`);
    expect(await query.list(nobody)).toEqual([]);
  });
});
