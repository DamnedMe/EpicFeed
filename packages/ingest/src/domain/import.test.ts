import { describe, expect, it } from 'vitest';
import type { ImportedPart, LessonImport } from './import.js';
import { MAX_PARTS_PER_LESSON, normalizeLessonImport } from './import.js';

const video = (epicodeId: string, position: number): ImportedPart => ({
  epicodeId,
  title: `  Parte\t${epicodeId} `,
  position,
  kind: 'video',
  videoId: ' 1034168708 ',
  content: { kind: 'video', summaries: { it: 'Riassunto' } },
});

const lesson = (parts: ImportedPart[]): LessonImport => ({
  path: {
    studyProgram: { epicodeId: '5', title: 'EIT' },
    edition: { label: '2024/25' },
    subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
    chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
    lesson: { epicodeId: '66863', title: 'Binary trees', position: 1 },
  },
  parts,
});

describe('normalizeLessonImport', () => {
  it('normalizza titoli e id e ordina le parti per posizione', () => {
    const result = normalizeLessonImport(
      lesson([
        video('66866', 2),
        {
          epicodeId: '103064',
          title: 'Binary trees - Summary',
          position: 6,
          kind: 'reading',
          content: { kind: 'reading', markdown: '# Riassunto' },
        },
        video('66864', 0),
      ]),
    );
    expect(result.parts.map((p) => p.epicodeId)).toEqual(['66864', '66866', '103064']);
    expect(result.parts[0]).toMatchObject({ title: 'Parte 66864', videoId: '1034168708' });
    expect(result.parts[2]?.videoId).toBeUndefined();
    expect(result.path.chapter.title).toBe('3. Trees');
  });

  it('rifiuta una lezione senza parti o con troppe parti', () => {
    expect(() => normalizeLessonImport(lesson([]))).toThrow(
      expect.objectContaining({ code: 'INVALID_CONTENT' }),
    );
    const many = Array.from({ length: MAX_PARTS_PER_LESSON + 1 }, (_, i) => video(`${i}`, i));
    expect(() => normalizeLessonImport(lesson(many))).toThrow(/troppe parti/);
  });

  it('rifiuta parti duplicate', () => {
    expect(() => normalizeLessonImport(lesson([video('1', 0), video('1', 1)]))).toThrow(
      /stesso id/,
    );
  });

  it('rifiuta un tipo che non corrisponde al contenuto', () => {
    const wrong: ImportedPart = {
      ...video('1', 0),
      kind: 'reading',
      videoId: undefined,
    };
    expect(() => normalizeLessonImport(lesson([wrong]))).toThrow(/non corrisponde/);
  });

  it("rifiuta le slide, che non arrivano dall'estensione", () => {
    const slides: ImportedPart = {
      epicodeId: '8',
      title: 'Slide',
      position: 0,
      kind: 'slides',
      content: { kind: 'slides', fileName: 'a-1.pdf', pages: [{ number: 1, text: 'x' }] },
    };
    expect(() => normalizeLessonImport(lesson([slides]))).toThrow(/estensione/);
  });

  it('rifiuta un video su una parte di testo', () => {
    const wrong: ImportedPart = {
      epicodeId: '9',
      title: 'Testo',
      position: 0,
      kind: 'reading',
      videoId: '123',
      content: { kind: 'reading', markdown: 'x' },
    };
    expect(() => normalizeLessonImport(lesson([wrong]))).toThrow(/non ha video né sottotitoli/);
  });

  it('accetta un video senza riassunto se porta i sottotitoli, e normalizza le tracce', () => {
    const result = normalizeLessonImport(
      lesson([
        {
          ...video('1', 0),
          content: { kind: 'video', summaries: {} },
          subtitles: [
            {
              language: 'IT',
              autoGenerated: false,
              cues: [{ startMs: 0, endMs: 1, text: ' ciao ' }],
            },
          ],
        },
      ]),
    );
    expect(result.parts[0]?.subtitles).toEqual([
      { language: 'it', autoGenerated: false, cues: [{ startMs: 0, endMs: 1, text: 'ciao' }] },
    ]);
  });

  it('rifiuta un video senza riassunti né sottotitoli', () => {
    expect(() =>
      normalizeLessonImport(
        lesson([{ ...video('1', 0), content: { kind: 'video', summaries: { it: '  ' } } }]),
      ),
    ).toThrow(/né riassunti né sottotitoli/);
  });

  it('rifiuta tracce duplicate o troppe tracce', () => {
    const cue = [{ startMs: 0, endMs: 1, text: 'x' }];
    const it1 = { language: 'it', autoGenerated: false, cues: cue };
    expect(() =>
      normalizeLessonImport(
        lesson([{ ...video('1', 0), subtitles: [it1, { ...it1, language: 'IT' }] }]),
      ),
    ).toThrow(/stessa lingua/);
    const many = ['it', 'en', 'fr', 'de', 'es'].map((language) => ({ ...it1, language }));
    expect(() => normalizeLessonImport(lesson([{ ...video('1', 0), subtitles: many }]))).toThrow(
      /Troppe tracce/,
    );
  });

  it('rifiuta id, titoli ed edizioni non validi', () => {
    const base = lesson([video('1', 0)]);
    expect(() =>
      normalizeLessonImport({
        ...base,
        path: { ...base.path, studyProgram: { epicodeId: '../x', title: 'EIT' } },
      }),
    ).toThrow(expect.objectContaining({ code: 'INVALID_ID' }));
    expect(() =>
      normalizeLessonImport({
        ...base,
        path: { ...base.path, edition: { label: 'x'.repeat(65) } },
      }),
    ).toThrow(expect.objectContaining({ code: 'INVALID_TEXT' }));
    expect(() =>
      normalizeLessonImport({
        ...base,
        path: { ...base.path, lesson: { epicodeId: '1', title: 'L', position: -1 } },
      }),
    ).toThrow(expect.objectContaining({ code: 'INVALID_POSITION' }));
    expect(() => normalizeLessonImport(lesson([{ ...video('1', 0), videoId: 'abc' }]))).toThrow(
      /video non valido/,
    );
  });
});
