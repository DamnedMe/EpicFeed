import { beforeEach, describe, expect, it } from 'vitest';
import type {
  CatalogPath,
  ContentVersion,
  Entitlement,
  StoredSubtitleTrack,
  SubtitleAccess,
  CatalogRepository,
  CatalogTransaction,
  EntitlementVerifier,
  LessonPartInput,
  NewContentVersion,
} from '@epicfeed/catalog';
import type { LessonImport } from '../domain/import.js';
import type {
  ContentVersionId,
  LessonId,
  LessonPartId,
  SubtitleTrackId,
  UserId,
} from '@epicfeed/shared';
import { PossessionProofVerifier } from '@epicfeed/catalog';
import { ImportLesson } from './import-lesson.js';

const anna = '0a0a0a0a-0000-4000-8000-00000000000a' as UserId;
const bruno = '0b0b0b0b-0000-4000-8000-00000000000b' as UserId;
const now = new Date('2026-11-15T12:00:00Z');
const clock = { now: () => now };

interface State {
  lessons: Map<string, { id: LessonId; path: CatalogPath }>;
  parts: Map<string, { id: LessonPartId; input: LessonPartInput }>;
  versions: ContentVersion[];
  entitlements: Entitlement[];
  tracks: StoredSubtitleTrack[];
  access: SubtitleAccess[];
}

/**
 * Doppio in memoria del catalogo. La transazione lavora su una copia dello
 * stato e la conferma solo se il lavoro termina senza errori.
 */
class InMemoryCatalog implements CatalogRepository {
  state: State = {
    lessons: new Map(),
    parts: new Map(),
    versions: [],
    entitlements: [],
    tracks: [],
    access: [],
  };
  private seq = 0;

  private nextId(): string {
    this.seq += 1;
    return `00000000-0000-4000-8000-${String(this.seq).padStart(12, '0')}`;
  }

  async transaction<T>(work: (tx: CatalogTransaction) => Promise<T>): Promise<T> {
    const draft: State = {
      lessons: new Map(this.state.lessons),
      parts: new Map(this.state.parts),
      versions: [...this.state.versions],
      entitlements: [...this.state.entitlements],
      tracks: [...this.state.tracks],
      access: [...this.state.access],
    };
    const tx: CatalogTransaction = {
      upsertLessonPath: async (path) => {
        const key = path.lesson.epicodeId;
        const id = draft.lessons.get(key)?.id ?? (this.nextId() as LessonId);
        draft.lessons.set(key, { id, path });
        return Promise.resolve(id);
      },
      upsertLessonPart: async (lessonId, input) => {
        const key = `${lessonId}/${input.epicodeId}`;
        const id = draft.parts.get(key)?.id ?? (this.nextId() as LessonPartId);
        draft.parts.set(key, { id, input });
        return Promise.resolve(id);
      },
      findOrCreateVersion: async (input: NewContentVersion) => {
        const found = draft.versions.find(
          (v) => v.lessonPartId === input.lessonPartId && v.contentHash === input.contentHash,
        );
        if (found) return Promise.resolve({ version: found, created: false });
        const version: ContentVersion = {
          id: this.nextId() as ContentVersionId,
          lessonPartId: input.lessonPartId,
          contentHash: input.contentHash,
          firstSeenAt: input.firstSeenAt,
          generationStatus: 'pending',
        };
        draft.versions.push(version);
        return Promise.resolve({ version, created: true });
      },
      saveEntitlement: async (entitlement) => {
        const exists = draft.entitlements.some(
          (e) =>
            e.userId === entitlement.userId && e.contentVersionId === entitlement.contentVersionId,
        );
        if (!exists) draft.entitlements.push(entitlement);
        return Promise.resolve(!exists);
      },
      findOrCreateSubtitleTrack: async (input) => {
        const found = draft.tracks.find(
          (t) => t.lessonPartId === input.lessonPartId && t.contentHash === input.contentHash,
        );
        if (found) return Promise.resolve({ track: found, created: false });
        const track: StoredSubtitleTrack = {
          id: this.nextId() as SubtitleTrackId,
          lessonPartId: input.lessonPartId,
          language: input.track.language,
          autoGenerated: input.track.autoGenerated,
          contentHash: input.contentHash,
          firstSeenAt: input.firstSeenAt,
        };
        draft.tracks.push(track);
        return Promise.resolve({ track, created: true });
      },
      saveSubtitleAccess: async (access) => {
        const exists = draft.access.some(
          (a) => a.userId === access.userId && a.subtitleTrackId === access.subtitleTrackId,
        );
        if (!exists) draft.access.push(access);
        return Promise.resolve(!exists);
      },
    };
    const result = await work(tx);
    this.state = draft;
    return result;
  }
}

function lessonImport(
  summary: string,
  markdown = '# Binary trees - Summary',
  subtitle = 'Un albero binario ha al massimo due figli',
): LessonImport {
  return {
    path: {
      studyProgram: { epicodeId: '5', title: 'EIT' },
      edition: { label: '2024/25' },
      subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
      chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
      lesson: { epicodeId: '66863', title: 'Binary trees', position: 1 },
    },
    parts: [
      {
        epicodeId: '66864',
        title: 'Properties of binary trees',
        position: 0,
        kind: 'video',
        videoId: '1034168708',
        content: { kind: 'video', summaries: { it: summary } },
        subtitles: [
          {
            language: 'it',
            autoGenerated: false,
            cues: [{ startMs: 0, endMs: 2000, text: subtitle }],
          },
        ],
      },
      {
        epicodeId: '103064',
        title: 'Binary trees - Summary',
        position: 6,
        kind: 'reading',
        content: { kind: 'reading', markdown },
      },
    ],
  };
}

let catalog: InMemoryCatalog;
let importLesson: ImportLesson;

beforeEach(() => {
  catalog = new InMemoryCatalog();
  importLesson = new ImportLesson({
    catalog,
    verifier: new PossessionProofVerifier(clock),
    clock,
  });
});

describe('ImportLesson', () => {
  it('al primo import crea lezione, parti, versioni e permessi', async () => {
    const result = await importLesson.execute(anna, lessonImport('Un albero binario…'));
    expect(result.parts).toHaveLength(2);
    expect(result.parts.every((p) => p.newVersion && p.newEntitlement)).toBe(true);
    expect(result.parts.every((p) => p.generationStatus === 'pending')).toBe(true);
    expect(catalog.state.versions).toHaveLength(2);
    expect(catalog.state.entitlements.map((e) => e.userId)).toEqual([anna, anna]);
    expect(catalog.state.versions[0]?.firstSeenAt).toEqual(now);
  });

  it('un secondo import identico non crea duplicati', async () => {
    const first = await importLesson.execute(anna, lessonImport('Un albero binario…'));
    const second = await importLesson.execute(anna, lessonImport('Un albero binario…\r\n'));
    expect(second.lessonId).toBe(first.lessonId);
    expect(second.parts.map((p) => p.contentVersionId)).toEqual(
      first.parts.map((p) => p.contentVersionId),
    );
    expect(second.parts.some((p) => p.newVersion || p.newEntitlement)).toBe(false);
    expect(catalog.state.versions).toHaveLength(2);
    expect(catalog.state.entitlements).toHaveLength(2);
  });

  it('un altro studente con lo stesso contenuto riceve il permesso senza duplicare la versione', async () => {
    await importLesson.execute(anna, lessonImport('Un albero binario…'));
    const result = await importLesson.execute(bruno, lessonImport('Un albero binario…'));
    expect(result.parts.every((p) => !p.newVersion && p.newEntitlement)).toBe(true);
    expect(catalog.state.versions).toHaveLength(2);
    expect(catalog.state.entitlements.filter((e) => e.userId === bruno)).toHaveLength(2);
  });

  it('un contenuto cambiato crea una nuova versione solo per la parte cambiata', async () => {
    const first = await importLesson.execute(anna, lessonImport('Versione 1'));
    const second = await importLesson.execute(anna, lessonImport('Versione 2'));
    expect(second.parts[0]?.newVersion).toBe(true);
    expect(second.parts[0]?.contentVersionId).not.toBe(first.parts[0]?.contentVersionId);
    expect(second.parts[0]?.lessonPartId).toBe(first.parts[0]?.lessonPartId);
    expect(second.parts[1]?.newVersion).toBe(false);
    expect(catalog.state.versions).toHaveLength(3);
  });

  it('salva i sottotitoli a parte: una traccia corretta non crea una nuova versione', async () => {
    const first = await importLesson.execute(anna, lessonImport('Riassunto'));
    expect(first.parts[0]?.subtitles).toMatchObject([{ language: 'it', newTrack: true }]);
    const again = await importLesson.execute(bruno, lessonImport('Riassunto'));
    expect(again.parts[0]?.subtitles[0]?.newTrack).toBe(false);
    expect(catalog.state.access.map((a) => a.userId)).toEqual([anna, bruno]);

    const fixed = await importLesson.execute(
      anna,
      lessonImport('Riassunto', undefined, 'Testo corretto'),
    );
    expect(fixed.parts[0]?.newVersion).toBe(false);
    expect(fixed.parts[0]?.subtitles[0]?.newTrack).toBe(true);
    expect(catalog.state.tracks).toHaveLength(2);
    expect(catalog.state.versions).toHaveLength(2);
  });

  it('se il verificatore nega il permesso non salva nulla', async () => {
    const denying: EntitlementVerifier = {
      verify: () => Promise.reject(new Error('negato')),
    };
    const guarded = new ImportLesson({ catalog, verifier: denying, clock });
    await expect(guarded.execute(anna, lessonImport('X'))).rejects.toThrow('negato');
    expect(catalog.state.versions).toHaveLength(0);
    expect(catalog.state.lessons.size).toBe(0);
  });

  it('rifiuta un contenuto non valido prima di aprire la transazione', async () => {
    let opened = false;
    const spy: CatalogRepository = {
      transaction: () => {
        opened = true;
        return Promise.reject(new Error('non doveva aprire'));
      },
    };
    const guarded = new ImportLesson({
      catalog: spy,
      verifier: new PossessionProofVerifier(clock),
      clock,
    });
    await expect(guarded.execute(anna, lessonImport('ok', '   '))).rejects.toMatchObject({
      code: 'INVALID_CONTENT',
    });
    expect(opened).toBe(false);
  });
});
