import type { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { LessonFeedDraft } from '../domain/feed.js';
import type { LessonId, UserId } from '@epicfeed/shared';
import type { LessonImport } from '@epicfeed/ingest';
import { ImportLesson } from '@epicfeed/ingest';
import { ImportLessonSlides } from '../application/slides.js';
import {
  ListLessonsToGenerate,
  ListOwnedLessons,
  ReadLessonForGeneration,
  SaveLessonFeed,
} from '../application/generation.js';
import { PossessionProofVerifier } from '@epicfeed/catalog';
import { DrizzleCatalogRepository } from '@epicfeed/catalog/infrastructure';
import { DrizzleGenerationRepository } from './generation-repository.js';
import { setupTestDatabase as setup, TEST_USERS } from '@epicfeed/db/testing';
import type { Database } from '@epicfeed/db';

const { anna, bruno } = TEST_USERS;

let pg: PGlite;
let db: Database;
let repository: DrizzleGenerationRepository;
let importLesson: ImportLesson;
let lessonId: LessonId;
let now = new Date('2026-11-21T19:00:00Z');
const clock = { now: () => now };

const lines = [
  ...Array.from({ length: 8 }, (_, i) => `osservazione generica numero ${i} sulle liste`),
  'un albero AVL è un albero binario di ricerca che si ribilancia da solo',
  'il fattore di bilanciamento di ogni nodo resta al massimo uno',
  'dopo un inserimento serve una rotazione per ribilanciare',
  ...Array.from({ length: 8 }, (_, i) => `osservazione generica numero ${i + 8} sulle code`),
];

function lesson(summary: string): LessonImport {
  return {
    path: {
      studyProgram: { epicodeId: '5', title: 'EIT' },
      edition: { label: '2024/25' },
      subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
      chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
      lesson: { epicodeId: '66863', title: 'Binary trees', position: 1 },
    },
    parts: [
      {
        epicodeId: '66864',
        title: 'Binary trees & AVL trees',
        position: 0,
        kind: 'video',
        videoId: '1034168708',
        content: { kind: 'video', summaries: { it: summary, en: 'AVL summary' } },
        subtitles: [
          {
            language: 'it',
            autoGenerated: false,
            cues: lines.map((text, i) => ({ startMs: i * 5000, endMs: i * 5000 + 4000, text })),
          },
        ],
      },
      {
        epicodeId: '103064',
        title: 'Binary trees - Summary',
        position: 6,
        kind: 'reading',
        content: { kind: 'reading', markdown: '# Binary trees - Summary' },
      },
    ],
  };
}

const bi = (it: string, en: string) => ({ it, en });

function draft(videoPart: string, readingPart: string): LessonFeedDraft {
  const concept = 'avl-tree' as LessonFeedDraft['concepts'][number]['key'];
  const card = (id: string, part: string): LessonFeedDraft['cards'][number] => ({
    id,
    kind: 'concept',
    title: bi('Albero AVL', 'AVL tree'),
    keyPoint: bi(
      'Un albero binario di ricerca che si ribilancia da solo.',
      'A self-balancing BST.',
    ),
    body: bi(
      'Il fattore di bilanciamento resta al massimo uno grazie a una rotazione dopo ogni inserimento.',
      'The balance factor stays at most one thanks to a rotation after each insertion.',
    ),
    terms: ['AVL tree', 'balance factor'],
    conceptKeys: [concept],
    sourcePartId: part as LessonFeedDraft['cards'][number]['sourcePartId'],
    origin: part === videoPart ? 'summary' : 'reading',
  });
  const question = (id: string, answer: boolean): LessonFeedDraft['quiz'][number] => ({
    id,
    kind: 'true_false',
    question: bi('Un AVL è un BST?', 'Is an AVL a BST?'),
    answer,
    explanation: bi('Sì, bilanciato.', 'Yes, balanced.'),
    conceptKey: concept,
    difficulty: 1,
  });
  return {
    cards: [card('avl', videoPart), card('avl-2', videoPart), card('summary', readingPart)],
    quiz: [question('q1', true), question('q2', false)],
    concepts: [{ key: concept, name: bi('Albero AVL', 'AVL tree'), description: bi('BST', 'BST') }],
    glossary: [
      { term: 'Balance factor', translation: 'fattore di bilanciamento', definition: bi('a', 'b') },
    ],
  };
}

beforeAll(async () => {
  ({ pg, db } = await setup());
  repository = new DrizzleGenerationRepository(db);
  importLesson = new ImportLesson({
    catalog: new DrizzleCatalogRepository(db),
    verifier: new PossessionProofVerifier(clock),
    clock,
  });
  lessonId = (await importLesson.execute(anna as UserId, lesson('Riassunto AVL'))).lessonId;
});

afterAll(async () => {
  await pg.close();
});

const statuses = async () =>
  (
    await pg.query<{ generation_status: string }>(
      'select generation_status from content_versions order by first_seen_at, id',
    )
  ).rows.map((row) => row.generation_status);

describe('DrizzleGenerationRepository con i casi d’uso della generazione', () => {
  it('elenca la lezione da generare solo a chi la possiede', async () => {
    const list = new ListLessonsToGenerate(repository);
    const forAnna = await list.execute(anna as UserId, 10);
    expect(forAnna.lessons).toEqual([
      {
        lessonId,
        lessonTitle: 'Binary trees',
        chapterTitle: '3. Trees',
        subjectTitle: 'Data Structures and Algorithms',
        partCount: 2,
      },
    ]);
    expect((await list.execute(bruno as UserId, 10)).totals).toEqual({
      lessons: 0,
      ready: 0,
      toGenerate: 0,
    });
  });

  it('legge le fonti con sottotitoli e glossario e segna le versioni in generazione', async () => {
    const read = await new ReadLessonForGeneration(repository).execute(anna as UserId, lessonId);
    expect(read.parts.map((part) => part.kind)).toEqual(['video', 'reading']);
    expect(read.parts[0]?.subtitles[0]?.cues).toHaveLength(lines.length);
    expect(read.parts[0]?.content).toEqual({
      kind: 'video',
      summaries: { it: 'Riassunto AVL', en: 'AVL summary' },
    });
    expect(read.glossary).toEqual([]);
    expect(await statuses()).toEqual(['generating', 'generating']);
    await expect(
      new ReadLessonForGeneration(repository).execute(bruno as UserId, lessonId),
    ).rejects.toMatchObject({ code: 'NOT_FOUND' });
  });

  it('salva il feed una volta sola, con glossario, allineamento e versioni pronte', async () => {
    const read = await new ReadLessonForGeneration(repository).execute(anna as UserId, lessonId);
    const [video, reading] = read.parts;
    const save = new SaveLessonFeed({ repository, clock });
    const input = {
      lessonId,
      sourcesHash: read.sourcesHash,
      promptVersion: '2026-11-21.1',
      feed: draft(video?.lessonPartId ?? '', reading?.lessonPartId ?? ''),
    };
    const first = await save.execute(anna as UserId, input);
    expect(first).toMatchObject({ created: true, cards: 3, alignedCards: 3 });
    expect(await statuses()).toEqual(['ready', 'ready']);

    const second = await save.execute(anna as UserId, input);
    expect(second).toMatchObject({ created: false, feedId: first.feedId });

    const stored = (
      await pg.query<{ feed: { cards: { video: { startMs: number } | null }[] } }>(
        'select feed from lesson_feeds',
      )
    ).rows;
    expect(stored).toHaveLength(1);
    // Le righe sull'AVL iniziano a 40 s: il tratto le comprende.
    expect(stored[0]?.feed.cards[0]?.video?.startMs).toBeGreaterThanOrEqual(10_000);
    expect(stored[0]?.feed.cards[0]?.video?.startMs).toBeLessThanOrEqual(40_000);
    // La scheda della lettura trova il minuto nel video della lezione (ADR 0015).
    expect(stored[0]?.feed.cards[2]?.video).not.toBeNull();

    const reread = await new ReadLessonForGeneration(repository).execute(anna as UserId, lessonId);
    expect(reread.glossary.map((entry) => entry.term)).toEqual(['Balance factor']);
    // Le versioni pronte restano pronte anche se la lezione viene riletta.
    expect(await statuses()).toEqual(['ready', 'ready']);

    const list = await new ListLessonsToGenerate(repository).execute(anna as UserId, 10);
    expect(list.totals).toEqual({ lessons: 1, ready: 1, toGenerate: 0 });
  });

  it('un riassunto cambiato rimette la lezione tra quelle da generare', async () => {
    now = new Date('2026-11-22T10:00:00Z');
    await importLesson.execute(anna as UserId, lesson('Riassunto AVL aggiornato'));
    const list = await new ListLessonsToGenerate(repository).execute(anna as UserId, 10);
    expect(list.totals).toEqual({ lessons: 1, ready: 0, toGenerate: 1 });
    // Bruno importa la versione vecchia: il feed esistente vale anche per lui.
    await importLesson.execute(bruno as UserId, lesson('Riassunto AVL'));
    const forBruno = await new ListLessonsToGenerate(repository).execute(bruno as UserId, 10);
    expect(forBruno.totals).toEqual({ lessons: 1, ready: 1, toGenerate: 0 });
  });

  it('importa le slide di una lezione posseduta, senza doppioni, e le passa alla generazione', async () => {
    const importSlides = new ImportLessonSlides({
      catalog: new DrizzleCatalogRepository(db),
      generation: repository,
      verifier: new PossessionProofVerifier(clock),
      clock,
    });
    const deck = {
      number: 1,
      content: {
        kind: 'slides' as const,
        fileName: 'AVL trees-1.pdf',
        pages: [
          { number: 1, text: 'AVL trees' },
          { number: 2, text: '' },
        ],
      },
    };
    const first = await importSlides.execute(anna as UserId, lessonId, [deck]);
    expect(first[0]).toMatchObject({ number: 1, newVersion: true, pages: 2 });
    const again = await importSlides.execute(anna as UserId, lessonId, [deck]);
    expect(again[0]?.newVersion).toBe(false);

    const owned = await new ListOwnedLessons(repository).execute(anna as UserId);
    expect(owned).toEqual([expect.objectContaining({ lessonId, slides: 1 })]);
    const read = await new ReadLessonForGeneration(repository).execute(anna as UserId, lessonId);
    const slidesPart = read.parts.find((part) => part.kind === 'slides');
    expect(slidesPart?.content).toEqual(deck.content);
    expect(read.parts.at(-1)?.kind).toBe('slides');

    // Chi non ha importato la lezione non può aggiungerle slide.
    const stranger = '0c0c0c0c-0000-4000-8000-00000000000c' as UserId;
    await expect(importSlides.execute(stranger, lessonId, [deck])).rejects.toMatchObject({
      code: 'NOT_FOUND',
    });
  });
});
