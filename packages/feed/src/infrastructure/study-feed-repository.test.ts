import type { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { LessonFeedDraft } from '../domain/feed.js';
import type { LessonImport } from '@epicfeed/ingest';
import type { UserId } from '@epicfeed/shared';
import { ALIGNMENT_VERSION } from '../domain/alignment.js';
import {
  ListStudySubjects,
  ReadSubjectFeed,
  RealignLessonFeeds,
} from '../application/study-feed.js';
import { ReadLessonForGeneration, SaveLessonFeed } from '../application/generation.js';
import { ImportLesson } from '@epicfeed/ingest';
import { PossessionProofVerifier } from '@epicfeed/catalog';
import { DrizzleCatalogRepository } from '@epicfeed/catalog/infrastructure';
import { DrizzleGenerationRepository } from './generation-repository.js';
import { DrizzleStudyFeedRepository } from './study-feed-repository.js';
import { setupTestDatabase as setup, TEST_USERS } from '@epicfeed/db/testing';
import type { Database } from '@epicfeed/db';

const { anna, bruno } = TEST_USERS;

let pg: PGlite;
let db: Database;
let feeds: DrizzleStudyFeedRepository;
let generation: DrizzleGenerationRepository;
let subjectId: string;
const clock = { now: () => new Date('2026-11-23T10:00:00Z') };
const bi = (it: string, en: string) => ({ it, en });

const lines = [
  ...Array.from({ length: 8 }, (_, i) => `osservazione generica numero ${i} sulle liste`),
  'un albero AVL è un albero binario di ricerca che si ribilancia da solo',
  'il fattore di bilanciamento di ogni nodo resta al massimo uno',
  'dopo un inserimento serve una rotazione per ribilanciare',
  ...Array.from({ length: 8 }, (_, i) => `osservazione generica numero ${i + 8} sulle code`),
];

function lesson(epicodeId: string, title: string, position: number): LessonImport {
  return {
    path: {
      studyProgram: { epicodeId: '5', title: 'EIT' },
      edition: { label: '2024/25' },
      subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
      chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
      lesson: { epicodeId, title, position },
    },
    parts: [
      {
        epicodeId: `${epicodeId}1`,
        title: `${title} video`,
        position: 0,
        kind: 'video',
        videoId: '1034168708',
        content: { kind: 'video', summaries: { it: `Riassunto ${title}`, en: 'Summary' } },
        subtitles: [
          {
            language: 'it',
            autoGenerated: false,
            cues: lines.map((text, i) => ({ startMs: i * 5000, endMs: i * 5000 + 4000, text })),
          },
        ],
      },
      {
        epicodeId: `${epicodeId}2`,
        title: `${title} - Summary`,
        position: 1,
        kind: 'reading',
        content: { kind: 'reading', markdown: `# ${title}` },
      },
    ],
  };
}

function draft(readingPart: string): LessonFeedDraft {
  const concept = 'avl-tree' as LessonFeedDraft['concepts'][number]['key'];
  const question = (id: string): LessonFeedDraft['quiz'][number] => ({
    id,
    kind: 'true_false',
    question: bi('Un AVL è un BST?', 'Is an AVL a BST?'),
    answer: true,
    explanation: bi('Sì.', 'Yes.'),
    conceptKey: concept,
    difficulty: 1,
  });
  const card = (id: string): LessonFeedDraft['cards'][number] => ({
    id,
    kind: 'concept',
    title: bi('Albero AVL', 'AVL tree'),
    keyPoint: bi(
      'Un albero binario di ricerca che si ribilancia da solo.',
      'A self-balancing BST.',
    ),
    body: bi(
      'Il fattore di bilanciamento resta al massimo uno grazie a una rotazione dopo ogni inserimento.',
      'The balance factor stays at most one thanks to a rotation after each insertion.',
    ),
    terms: ['AVL tree', 'balance factor'],
    conceptKeys: [concept],
    sourcePartId: readingPart as LessonFeedDraft['cards'][number]['sourcePartId'],
    origin: 'reading',
  });
  return {
    cards: [card('a'), card('b'), card('c')],
    quiz: [question('q1'), question('q2')],
    concepts: [{ key: concept, name: bi('Albero AVL', 'AVL tree'), description: bi('BST', 'BST') }],
    glossary: [],
  };
}

beforeAll(async () => {
  ({ pg, db } = await setup());
  feeds = new DrizzleStudyFeedRepository(db);
  generation = new DrizzleGenerationRepository(db);
  const importLesson = new ImportLesson({
    catalog: new DrizzleCatalogRepository(db),
    verifier: new PossessionProofVerifier(clock),
    clock,
  });
  const first = await importLesson.execute(anna as UserId, lesson('66863', 'Binary trees', 1));
  await importLesson.execute(anna as UserId, lesson('66870', 'Heaps', 2));

  // Feed della prima lezione, salvato come in M2: senza versione e senza minuti.
  const read = await new ReadLessonForGeneration(generation).execute(
    anna as UserId,
    first.lessonId,
  );
  await new SaveLessonFeed({ repository: generation, clock }).execute(anna as UserId, {
    lessonId: first.lessonId,
    sourcesHash: read.sourcesHash,
    promptVersion: '2026-11-21.2',
    feed: draft(read.parts[1]?.lessonPartId ?? ''),
  });
  await pg.exec(`update lesson_feeds set feed = (feed - 'alignmentVersion') ||
    jsonb_build_object('cards', (select jsonb_agg(c || '{"video": null}') from jsonb_array_elements(feed->'cards') c))`);
  subjectId = (await pg.query<{ id: string }>('select id from subjects')).rows[0]?.id ?? '';
});

afterAll(async () => {
  await pg.close();
});

describe('DrizzleStudyFeedRepository', () => {
  it('elenca le materie con le lezioni pronte solo a chi le ha importate', async () => {
    const list = new ListStudySubjects(feeds);
    expect(await list.execute(anna as UserId)).toEqual([
      {
        subjectId,
        title: 'Data Structures and Algorithms',
        editionLabel: '2024/25',
        lessons: 2,
        lessonsWithFeed: 1,
      },
    ]);
    expect(await list.execute(bruno as UserId)).toEqual([]);
  });

  it('legge la materia in ordine con parti, link al portale e feed', async () => {
    const { feed, outdated } = await new ReadSubjectFeed(feeds).execute(anna as UserId, subjectId);
    const [binary, heaps] = feed.chapters[0]?.lessons ?? [];
    expect(binary?.title).toBe('Binary trees');
    expect(binary?.portalUrl).toBe('https://learn.epicode.edu.mt/course/177/curriculum/66863');
    expect(binary?.parts.map((part) => part.kind)).toEqual(['video', 'reading']);
    expect(binary?.feed?.cards).toHaveLength(3);
    expect(heaps?.feed).toBeNull();
    expect(outdated).toHaveLength(1);
    await expect(
      new ReadSubjectFeed(feeds).execute(bruno as UserId, subjectId),
    ).rejects.toMatchObject({ code: 'NOT_FOUND' });
  });

  it('riallinea i feed vecchi una volta sola', async () => {
    const read = new ReadSubjectFeed(feeds);
    const { outdated, feed: before } = await read.execute(anna as UserId, subjectId);
    const realign = new RealignLessonFeeds(generation, feeds);
    expect(await realign.execute(anna as UserId, outdated)).toEqual({
      updated: 1,
      alignedCards: 3,
    });
    // Una seconda richiesta con la stessa versione letta non scrive nulla.
    expect(await realign.execute(anna as UserId, outdated)).toEqual({
      updated: 0,
      alignedCards: 0,
    });

    const { outdated: after, feed } = await read.execute(anna as UserId, subjectId);
    expect(after).toEqual([]);
    expect(feed.version).not.toBe(before.version);
    const binary = feed.chapters[0]?.lessons[0]?.feed;
    expect(binary?.alignmentVersion).toBe(ALIGNMENT_VERSION);
    expect(binary?.cards[0]?.video?.partId).toBe(feed.chapters[0]?.lessons[0]?.parts[0]?.partId);
  });
});
