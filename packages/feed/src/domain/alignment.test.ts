import { describe, expect, it } from 'vitest';
import {
  alignCard,
  alignCardToLesson,
  alignToCues,
  cardQuery,
  studyLanguageOf,
  tokenize,
} from './alignment.js';
import type { ConceptKey, FeedCard } from './feed.js';
import type { LessonPartId } from '@epicfeed/shared';
import type { SubtitleCue, SubtitleTrack } from '@epicfeed/catalog';

/** Righe di 5 secondi l'una, a partire da 0. */
function cuesOf(lines: readonly string[]): SubtitleCue[] {
  return lines.map((text, i) => ({ startMs: i * 5000, endMs: i * 5000 + 4500, text }));
}

const filler = (n: number, topic: string): string[] =>
  Array.from({ length: n }, (_, i) => `${topic} discussion number ${i} with generic remarks`);

const englishLines = [
  ...filler(12, 'introduction'),
  'an AVL tree is a self balancing binary search tree',
  'the balance factor of every node is at most one',
  'when we insert we may need a rotation to rebalance',
  'a left rotation moves the right child up',
  ...filler(12, 'hashing'),
];

const avlCard: FeedCard = {
  id: 'avl',
  kind: 'concept',
  title: { it: 'Albero AVL', en: 'AVL tree' },
  keyPoint: { it: 'Un BST che si ribilancia da solo.', en: 'A self-balancing binary search tree.' },
  body: {
    it: 'Il fattore di bilanciamento resta al massimo 1 grazie alle rotazioni.',
    en: 'The balance factor stays at most one thanks to rotations after each insert.',
  },
  steps: { it: ['Inserisci'], en: ['Insert'] },
  comparison: {
    left: { it: 'Bilanciato', en: 'Balanced' },
    right: { it: 'Sbilanciato', en: 'Unbalanced' },
    rows: [
      {
        aspect: { it: 'Altezza', en: 'Height' },
        left: { it: 'log', en: 'log' },
        right: { it: 'n', en: 'n' },
      },
    ],
  },
  terms: ['AVL tree', 'balance factor', 'rotation'],
  conceptKeys: ['avl-tree' as ConceptKey],
  sourcePartId: '11111111-1111-4111-8111-111111111111' as LessonPartId,
  origin: 'summary',
};

describe('tokenize', () => {
  it('tiene le parole significative, senza accenti né parole frequenti, ridotte alla radice', () => {
    expect(tokenize('The Rotazioni perché è __init__ of trees, tree e alberi')).toEqual([
      'rotaz',
      'init',
      'tree',
      'tree',
      'alber',
    ]);
  });
});

describe('alignToCues', () => {
  it('trova il tratto in cui si parla della scheda, con un piccolo anticipo', () => {
    const result = alignToCues(cardQuery(avlCard, 'en'), cuesOf(englishLines));
    expect(result).not.toBeNull();
    // La finestra vincente include le righe 12–15 (60–80 s).
    expect(result?.startMs).toBeGreaterThanOrEqual(30_000);
    expect(result?.startMs).toBeLessThanOrEqual(60_000);
    expect(result?.endMs).toBeGreaterThanOrEqual(64_500);
    expect(result?.confidence).toBeGreaterThan(0.3);
  });

  it('restituisce null se le parole non compaiono nella traccia o la traccia è vuota', () => {
    expect(
      alignToCues({ texts: ['quicksort pivot partition'], terms: [] }, cuesOf(englishLines)),
    ).toBeNull();
    expect(alignToCues(cardQuery(avlCard, 'en'), [])).toBeNull();
  });

  it('restituisce null se le parole in comune sono troppo poche', () => {
    expect(alignToCues({ texts: ['rotation'], terms: [] }, cuesOf(englishLines))).toBeNull();
  });

  it("restituisce null se l'argomento torna in due punti lontani con forza simile", () => {
    const topic = 'avl tree balance factor rotation insert';
    const lines = [topic, ...filler(20, 'other'), topic];
    expect(alignToCues({ texts: [topic], terms: [] }, cuesOf(lines))).toBeNull();
  });

  it('non va sotto lo zero con l’anticipo', () => {
    const lines = ['avl tree balance factor rotation insert', ...filler(20, 'other')];
    expect(
      alignToCues({ texts: ['avl tree balance factor rotation'], terms: [] }, cuesOf(lines))
        ?.startMs,
    ).toBe(0);
  });
});

describe('alignCard', () => {
  const english: SubtitleTrack = {
    language: 'en-x-autogen',
    autoGenerated: true,
    cues: cuesOf(englishLines),
  };
  const italianLines = [
    ...filler(12, 'introduzione'),
    'un albero AVL è un BST che si ribilancia da solo',
    'il fattore di bilanciamento resta al massimo uno',
    'dopo un inserimento serve una rotazione',
    ...filler(12, 'hashing'),
  ];
  const italian: SubtitleTrack = {
    language: 'it',
    autoGenerated: false,
    cues: cuesOf(italianLines),
  };

  it('prova ogni traccia nella sua lingua e tiene il risultato migliore', () => {
    const result = alignCard(avlCard, [english, italian]);
    expect(result).not.toBeNull();
    expect(['it', 'en-x-autogen']).toContain(result?.language);
  });

  it('a parità di confidenza preferisce la traccia non automatica', () => {
    const autoIt: SubtitleTrack = { ...italian, language: 'it-x-autogen', autoGenerated: true };
    expect(alignCard(avlCard, [autoIt, italian])?.language).toBe('it');
    expect(alignCard(avlCard, [italian, autoIt])?.language).toBe('it');
  });

  it('ignora le lingue diverse da italiano e inglese e le tracce senza risultato', () => {
    const french: SubtitleTrack = {
      language: 'fr',
      autoGenerated: false,
      cues: cuesOf(englishLines),
    };
    const unrelated: SubtitleTrack = {
      language: 'en',
      autoGenerated: false,
      cues: cuesOf(filler(30, 'graphs')),
    };
    expect(alignCard(avlCard, [french, unrelated])).toBeNull();
  });
});

describe('studyLanguageOf', () => {
  it('riduce la lingua della traccia alla lingua di studio', () => {
    expect(studyLanguageOf('en-x-autogen')).toBe('en');
    expect(studyLanguageOf('IT')).toBe('it');
    expect(studyLanguageOf('fr')).toBeNull();
  });
});

describe('alignCardToLesson', () => {
  const avlVideo = '22222222-2222-4222-8222-222222222222' as LessonPartId;
  const hashVideo = '33333333-3333-4333-8333-333333333333' as LessonPartId;
  const slidesPart = '44444444-4444-4444-8444-444444444444' as LessonPartId;
  const track = (lines: readonly string[]): SubtitleTrack => ({
    language: 'en',
    autoGenerated: false,
    cues: cuesOf(lines),
  });
  const videos = [
    { partId: hashVideo, tracks: [track(filler(30, 'hashing'))] },
    { partId: avlVideo, tracks: [track(englishLines)] },
  ];

  it('trova il video giusto per una scheda tratta dalle slide', () => {
    const result = alignCardToLesson({ ...avlCard, sourcePartId: slidesPart }, videos);
    expect(result?.partId).toBe(avlVideo);
    expect(result?.startMs).toBeGreaterThan(30_000);
  });

  it('per una scheda da un video cerca solo in quel video', () => {
    expect(alignCardToLesson({ ...avlCard, sourcePartId: hashVideo }, videos)).toBeNull();
    expect(alignCardToLesson({ ...avlCard, sourcePartId: avlVideo }, videos)?.partId).toBe(
      avlVideo,
    );
  });

  it('senza video o senza tracce non propone nessun minuto', () => {
    expect(alignCardToLesson({ ...avlCard, sourcePartId: slidesPart }, [])).toBeNull();
    expect(
      alignCardToLesson({ ...avlCard, sourcePartId: slidesPart }, [
        { partId: avlVideo, tracks: [] },
      ]),
    ).toBeNull();
  });
});
