import type { ContentHash, Sha256 } from './content-hash.js';
import { hashCanonical, webCryptoSha256 } from './content-hash.js';
import { limitLength } from './content.js';
import { DomainError } from './errors.js';
import type { LessonPartId, SubtitleTrackId, UserId } from './ids.js';
import { normalizeText } from './text.js';

/**
 * Riga dei sottotitoli. I tempi sono in millisecondi interi, così il
 * confronto e l'impronta non dipendono da arrotondamenti dei decimali.
 */
export interface SubtitleCue {
  readonly startMs: number;
  readonly endMs: number;
  readonly text: string;
}

/**
 * Lingua di una traccia. Vimeo indica le tracce generate automaticamente con
 * il suffisso `-x-autogen` (es. `en-x-autogen`): lo teniamo, perché quelle
 * tracce sono le meno affidabili (ADR 0006).
 */
export type SubtitleLanguage = string;

/**
 * Traccia di sottotitoli di una parte video. È separata dalla versione del
 * contenuto: serve per i tempi delle schede e per qualche dettaglio, mai come
 * base del testo (ADR 0006). Come le versioni, è deduplicata per impronta e
 * visibile solo a chi l'ha importata (prova di possesso).
 */
export interface SubtitleTrack {
  readonly language: SubtitleLanguage;
  /** `true` se generata automaticamente (Vimeo: `provenance: ai_generated`). */
  readonly autoGenerated: boolean;
  readonly cues: readonly SubtitleCue[];
}

/** Limite di sicurezza sul numero di righe di una traccia (circa 6 ore di video). */
export const MAX_SUBTITLE_CUES = 10_000;
/** Massimo di tracce per parte video (sul portale: italiano e inglese automatico). */
export const MAX_SUBTITLE_TRACKS = 4;

const LANGUAGE_PATTERN = /^[a-z]{2,3}(-[a-z0-9]{1,8}){0,3}$/;

/**
 * Porta una traccia nella forma canonica: lingua in minuscolo, righe ordinate
 * per tempo, a capo interni uniti, righe vuote scartate.
 *
 * @param track - Traccia come arriva dall'import.
 * @returns La traccia canonica.
 * @throws {@link DomainError} `INVALID_CONTENT` se la lingua non è valida, se i
 *   tempi non sono interi coerenti, se è troppo lunga o se resta vuota.
 */
export function normalizeSubtitleTrack(track: SubtitleTrack): SubtitleTrack {
  const language = track.language.trim().toLowerCase();
  if (!LANGUAGE_PATTERN.test(language)) {
    throw new DomainError('INVALID_CONTENT', 'Lingua dei sottotitoli non valida');
  }
  if (track.cues.length > MAX_SUBTITLE_CUES) {
    throw new DomainError('INVALID_CONTENT', 'Troppe righe di sottotitoli');
  }
  const cues = track.cues
    .map(normalizeCue)
    .filter((cue) => cue.text.length > 0)
    .sort((a, b) => a.startMs - b.startMs || a.endMs - b.endMs);
  if (cues.length === 0) {
    throw new DomainError('INVALID_CONTENT', 'La traccia di sottotitoli è vuota');
  }
  return { language, autoGenerated: track.autoGenerated, cues };
}

function normalizeCue(cue: SubtitleCue): SubtitleCue {
  const { startMs, endMs } = cue;
  if (
    !Number.isSafeInteger(startMs) ||
    !Number.isSafeInteger(endMs) ||
    startMs < 0 ||
    endMs < startMs
  ) {
    throw new DomainError('INVALID_CONTENT', 'Tempi dei sottotitoli non validi');
  }
  // Nei sottotitoli gli a capo sono solo impaginazione: li uniamo in una riga.
  const text = limitLength(normalizeText(cue.text).replace(/\s*\n\s*/g, ' '), 'Sottotitolo');
  return { startMs, endMs, text };
}

/**
 * Impronta di una traccia: normalizza, serializza in JSON canonico e applica
 * SHA-256. La stessa traccia importata da più studenti si salva una volta sola.
 *
 * @param track - Traccia (anche non normalizzata).
 * @param sha256 - Implementazione del digest; di default la Web Crypto API.
 * @returns L'impronta esadecimale.
 * @throws {@link DomainError} se la traccia non è valida.
 */
export async function computeSubtitleTrackHash(
  track: SubtitleTrack,
  sha256: Sha256 = webCryptoSha256,
): Promise<ContentHash> {
  return hashCanonical(normalizeSubtitleTrack(track), sha256);
}

/** Traccia salvata nel catalogo, identificata dalla sua impronta. */
export interface StoredSubtitleTrack {
  readonly id: SubtitleTrackId;
  readonly lessonPartId: LessonPartId;
  readonly language: SubtitleLanguage;
  readonly autoGenerated: boolean;
  readonly contentHash: ContentHash;
  readonly firstSeenAt: Date;
}

/**
 * Permesso di uno studente su una traccia. Come per le versioni, si ottiene
 * solo presentando la traccia stessa: l'impronta la calcola il server.
 */
export interface SubtitleAccess {
  readonly userId: UserId;
  readonly subtitleTrackId: SubtitleTrackId;
  readonly grantedAt: Date;
}
