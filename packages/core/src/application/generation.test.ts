/** Repository in memoria, che registra le chiamate. */
class FakeRepository implements GenerationRepository {
  owned: OwnedLesson[] = [];
  feeds: { lessonId: LessonId; sourcesHash: ContentHash }[] = [];
  sources: LessonSources | null = sources;
  statusCalls: {
    ids: readonly ContentVersionId[];
    to: GenerationStatus;
    from: readonly GenerationStatus[];
  }[] = [];
  saved: NewLessonFeed[] = [];

  listOwnedLessons() {
    return Promise.resolve(this.owned);
  }
  listVisibleFeeds() {
    return Promise.resolve(this.feeds);
  }
  loadLessonSources(_user: UserId, id: LessonId) {
    return Promise.resolve(this.sources?.lessonId === id ? this.sources : null);
  }
  setGenerationStatus(
    ids: readonly ContentVersionId[],
    to: GenerationStatus,
    from: readonly GenerationStatus[],
  ) {
    this.statusCalls.push({ ids, to, from });
    return Promise.resolve();
  }
  saveLessonFeed(input: NewLessonFeed) {
    this.saved.push(input);
    return Promise.resolve({ feedId: 'feed-1', created: this.saved.length === 1 });
  }
}

describe('ListOwnedLessons', () => {
  it('elenca le lezioni importate con il numero di presentazioni di slide', async () => {
    const repo = new FakeRepository();
    repo.owned = [
      {
        lessonId,
        lessonTitle: 'AVL trees',
        chapterTitle: 'Trees',
        subjectTitle: 'DSA',
        sources: [
          { lessonPartId: videoPart, contentHash: hash('a'), kind: 'video' },
          { lessonPartId: readingPart, contentHash: hash('b'), kind: 'slides' },
        ],
      },
    ];
    expect(await new ListOwnedLessons(repo).execute(user)).toEqual([
      { lessonId, lessonTitle: 'AVL trees', chapterTitle: 'Trees', subjectTitle: 'DSA', slides: 1 },
    ]);
  });
});

describe('ListLessonsToGenerate', () => {
  it('elenca solo le lezioni senza un feed per le fonti attuali, con i totali', async () => {
    const repo = new FakeRepository();
    const lessonSources = [
      { lessonPartId: videoPart, contentHash: hash('a'), kind: 'video' as const },
    ];
    const base = { chapterTitle: 'Trees', subjectTitle: 'DSA', sources: lessonSources };
    repo.owned = [
      { ...base, lessonId, lessonTitle: 'Generata' },
      { ...base, lessonId: otherLesson, lessonTitle: 'Da generare' },
    ];
    repo.feeds = [
      { lessonId, sourcesHash: await computeLessonSourcesHash(lessonSources) },
      // Un feed vecchio della seconda lezione non conta: le fonti sono cambiate.
      { lessonId: otherLesson, sourcesHash: hash('0') },
    ];
    const result = await new ListLessonsToGenerate(repo).execute(user, 10);
    expect(result.lessons.map((lesson) => lesson.lessonTitle)).toEqual(['Da generare']);
    expect(result.lessons[0]?.partCount).toBe(1);
    expect(result.totals).toEqual({ lessons: 2, ready: 1, toGenerate: 1 });
    expect((await new ListLessonsToGenerate(repo).execute(user, 0)).lessons).toEqual([]);
  });
});

describe('ReadLessonForGeneration', () => {
  it('restituisce le fonti con l’impronta e segna le versioni in generazione', async () => {
    const repo = new FakeRepository();
    const result = await new ReadLessonForGeneration(repo).execute(user, lessonId);
    expect(result.sourcesHash).toBe(await computeLessonSourcesHash(sources.parts));
    expect(repo.statusCalls).toEqual([
      { ids: [v1, v2], to: 'generating', from: ['pending', 'failed'] },
    ]);
  });

  it('rifiuta una lezione non posseduta', async () => {
    const repo = new FakeRepository();
    await expect(
      new ReadLessonForGeneration(repo).execute(user, otherLesson),
    ).rejects.toMatchObject({
      code: 'NOT_FOUND',
    });
    repo.sources = { ...sources, parts: [] };
    await expect(new ReadLessonForGeneration(repo).execute(user, lessonId)).rejects.toThrow(
      DomainError,
    );
  });
});

describe('SaveLessonFeed', () => {
  const input = async () => ({
    lessonId,
    sourcesHash: await computeLessonSourcesHash(sources.parts),
    promptVersion: '2026-11-21.1',
    feed,
  });

  it('allinea le schede ai video della lezione, salva e passa le versioni a ready', async () => {
    const repo = new FakeRepository();
    const result = await new SaveLessonFeed({ repository: repo, clock }).execute(
      user,
      await input(),
    );
    expect(result).toEqual({ feedId: 'feed-1', created: true, cards: 3, alignedCards: 3 });
    const saved = repo.saved[0];
    expect(saved?.document.generatedAt).toBe('2026-11-21T19:00:00.000Z');
    expect(saved?.document.alignmentVersion).toBe(ALIGNMENT_VERSION);
    expect(saved?.document.cards[0]?.video?.language).toBe('en-x-autogen');
    // La scheda della lettura trova il minuto nel video della stessa lezione (ADR 0015).
    expect(saved?.document.cards[1]?.video?.partId).toBe(videoPart);
    expect(saved?.sourceVersionIds).toEqual([v1, v2]);
    expect(saved?.glossary).toHaveLength(1);
    expect(saved?.readyFrom).toEqual(['generating']);
    expect(saved?.generatedBy).toBe(user);
  });

  it('una parte video senza sottotitoli non viene allineata', async () => {
    const repo = new FakeRepository();
    const noSubs = sources.parts.map((part) => ({ ...part, subtitles: [] }));
    repo.sources = { ...sources, parts: noSubs };
    const result = await new SaveLessonFeed({ repository: repo, clock }).execute(user, {
      ...(await input()),
      sourcesHash: await computeLessonSourcesHash(noSubs),
    });
    expect(result.alignedCards).toBe(0);
  });

  it('rifiuta il feed se le fonti sono cambiate dopo la lettura', async () => {
    const repo = new FakeRepository();
    await expect(
      new SaveLessonFeed({ repository: repo, clock }).execute(user, {
        ...(await input()),
        sourcesHash: hash('9'),
      }),
    ).rejects.toMatchObject({ code: 'SOURCES_CHANGED' });
    expect(repo.saved).toEqual([]);
  });

  it('rifiuta una lezione non posseduta', async () => {
    const repo = new FakeRepository();
    repo.sources = null;
    await expect(
      new SaveLessonFeed({ repository: repo, clock }).execute(user, await input()),
    ).rejects.toMatchObject({
      code: 'NOT_FOUND',
    });
  });

  it('restituisce tutti i problemi del feed senza salvare', async () => {
    const repo = new FakeRepository();
    const broken = {
      ...feed,
      cards: [card('x', '20000000-0000-4000-8000-000000000009' as LessonPartId)],
    };
    const error = await new SaveLessonFeed({ repository: repo, clock })
      .execute(user, { ...(await input()), feed: broken })
      .catch((e: unknown) => e);
    expect(error).toBeInstanceOf(FeedValidationError);
    expect((error as FeedValidationError).issues.map((issue) => issue.path)).toEqual(
      expect.arrayContaining(['cards', 'cards[0].sourcePartId']),
    );
    expect(repo.saved).toEqual([]);
  });
});
