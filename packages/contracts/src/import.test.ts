import { describe, expect, it } from 'vitest';
import { importLessonRequestSchema, importLessonResponseSchema } from './import.js';

const valid = {
  path: {
    studyProgram: { epicodeId: '5', title: 'EIT' },
    edition: { label: '2024/25' },
    subject: { epicodeId: '177', title: 'Data Structures and Algorithms', position: 0 },
    chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
    lesson: { epicodeId: '66863', title: 'Binary trees', position: 1 },
  },
  parts: [
    {
      epicodeId: '66864',
      title: 'Properties of binary trees',
      position: 0,
      kind: 'video',
      videoId: '1034168708',
      content: {
        kind: 'video',
        summaries: { it: '# Alberi binari', en: '# Binary trees' },
      },
      subtitles: [
        { language: 'it', autoGenerated: false, cues: [{ startMs: 0, endMs: 1500, text: 'Ciao' }] },
      ],
    },
    {
      epicodeId: '103064',
      title: 'Binary trees - Summary',
      position: 6,
      kind: 'reading',
      content: { kind: 'reading', markdown: '# Riassunto' },
    },
  ],
};

describe('importLessonRequestSchema', () => {
  it('accetta una lezione valida', () => {
    expect(importLessonRequestSchema.parse(valid)).toEqual(valid);
  });

  it('rifiuta campi non previsti (niente dati in più dal portale)', () => {
    const extra = { ...valid, enrollments: [{ user: 'x' }] };
    expect(importLessonRequestSchema.safeParse(extra).success).toBe(false);
    const extraInPart = {
      ...valid,
      parts: [{ ...valid.parts[1], owner: 'qualcuno' }],
    };
    expect(importLessonRequestSchema.safeParse(extraInPart).success).toBe(false);
  });

  it('rifiuta id non sicuri, liste vuote e contenuti di tipo sconosciuto', () => {
    const badId = structuredClone(valid);
    badId.path.lesson.epicodeId = '1; drop table';
    expect(importLessonRequestSchema.safeParse(badId).success).toBe(false);
    expect(importLessonRequestSchema.safeParse({ ...valid, parts: [] }).success).toBe(false);
    const badKind = { ...valid, parts: [{ ...valid.parts[1], content: { kind: 'quiz' } }] };
    expect(importLessonRequestSchema.safeParse(badKind).success).toBe(false);
  });

  it('rifiuta tempi non interi nei sottotitoli', () => {
    const [first] = valid.parts;
    const bad = {
      ...valid,
      parts: [
        {
          ...first,
          subtitles: [
            { language: 'it', autoGenerated: false, cues: [{ startMs: 1.5, endMs: 2, text: 'x' }] },
          ],
        },
      ],
    };
    expect(importLessonRequestSchema.safeParse(bad).success).toBe(false);
  });
});

describe('importLessonResponseSchema', () => {
  it('valida la risposta del server', () => {
    const response = {
      lessonId: '00000000-0000-4000-8000-000000000001',
      parts: [
        {
          epicodeId: '66864',
          lessonPartId: '00000000-0000-4000-8000-000000000002',
          contentVersionId: '00000000-0000-4000-8000-000000000003',
          newVersion: true,
          newEntitlement: true,
          generationStatus: 'pending',
          subtitles: [],
        },
      ],
    };
    expect(importLessonResponseSchema.parse(response)).toEqual(response);
  });
});
