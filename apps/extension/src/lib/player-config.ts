/** Traccia di sottotitoli annunciata dal player Vimeo. */
export interface PlayerTrack {
  language: string;
  url: string;
  autoGenerated: boolean;
}

// Validazione a mano, senza zod: questo modulo gira nello script del player
// Vimeo, che deve restare leggero.
function record(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null ? (value as Record<string, unknown>) : null;
}

/**
 * Estrae l'oggetto assegnato a `window.playerConfig` dal codice di una pagina
 * del player Vimeo. Si legge il testo degli script (lo script di contenuto non
 * vede le variabili della pagina) e si isola l'oggetto contando le parentesi,
 * con attenzione alle stringhe.
 *
 * @param scriptText - Testo degli script della pagina del player.
 * @returns L'oggetto di configurazione, oppure `null` se non c'è.
 */
export function extractPlayerConfig(scriptText: string): unknown {
  const marker = /window\.playerConfig\s*=\s*\{/.exec(scriptText);
  if (!marker) return null;
  const start = marker.index + marker[0].length - 1;
  let depth = 0;
  let inString = false;
  for (let i = start; i < scriptText.length; i += 1) {
    const char = scriptText[i];
    if (inString) {
      if (char === '\\') i += 1;
      else if (char === '"') inString = false;
    } else if (char === '"') inString = true;
    else if (char === '{') depth += 1;
    else if (char === '}') {
      depth -= 1;
      if (depth === 0) {
        try {
          return JSON.parse(scriptText.slice(start, i + 1)) as unknown;
        } catch {
          return null;
        }
      }
    }
  }
  return null;
}

/**
 * Elenca le tracce di sottotitoli dalla configurazione del player.
 * Accetta solo URL dei sottotitoli di Vimeo (`captions.vimeo.com`).
 *
 * @param config - Oggetto restituito da {@link extractPlayerConfig}.
 * @returns Le tracce (vuoto se la configurazione non ne ha o non è riconosciuta).
 */
export function tracksFromConfig(config: unknown): PlayerTrack[] {
  const tracks = record(record(config)?.request)?.text_tracks;
  if (!Array.isArray(tracks)) return [];
  const result: PlayerTrack[] = [];
  for (const item of tracks) {
    const track = record(item);
    const lang = track?.lang;
    const url = track?.url;
    if (typeof lang !== 'string' || typeof url !== 'string') continue;
    let host: string;
    try {
      host = new URL(url).hostname;
    } catch {
      continue;
    }
    if (host !== 'captions.vimeo.com') continue;
    result.push({
      language: lang.toLowerCase(),
      url,
      autoGenerated: track?.provenance === 'ai_generated' || lang.includes('autogen'),
    });
  }
  return result;
}
