import { describe, expect, it, vi } from 'vitest';
import type { ImportLessonRequest } from '@study-feed/contracts';
import { runImportJob, type ImportJobDeps } from './import-job';
import type { ImportStatus, LessonPreview } from './messages';

const request: ImportLessonRequest = {
  path: {
    studyProgram: { epicodeId: '5', title: 'EIT' },
    edition: { label: '2024/25' },
    subject: { epicodeId: '177', title: 'DSA', position: 0 },
    chapter: { epicodeId: '66855', title: '3. Trees', position: 2 },
    lesson: { epicodeId: '66863', title: 'Binary trees', position: 1 },
  },
  parts: [
    {
      epicodeId: '1',
      title: 'Con riassunto',
      position: 0,
      kind: 'video',
      videoId: '11',
      content: { kind: 'video', summaries: { it: 'R' } },
    },
    {
      epicodeId: '2',
      title: 'Senza riassunto',
      position: 1,
      kind: 'video',
      videoId: '22',
      content: { kind: 'video', summaries: {} },
    },
  ],
};
const preview: LessonPreview = {
  request,
  videos: [
    { partEpicodeId: '1', videoId: '11' },
    { partEpicodeId: '2', videoId: '22' },
  ],
  skipped: 0,
};
const connection = {
  token: `sfi_${'C'.repeat(43)}`,
  expiresAt: '2099-01-01T00:00:00Z',
  apiBaseUrl: 'https://app.test',
};
const okResponse = {
  lessonId: '00000000-0000-4000-8000-000000000001',
  parts: [],
};

function deps(overrides: Partial<ImportJobDeps> = {}) {
  const statuses: ImportStatus[] = [];
  let sent: ImportLessonRequest | undefined;
  const base: ImportJobDeps = {
    loadTracks: (videoId) =>
      Promise.resolve(
        videoId === '11'
          ? [{ language: 'it', url: 'https://captions.vimeo.com/1.vtt', autoGenerated: false }]
          : null,
      ),
    fetchText: () => Promise.resolve('WEBVTT\n\n00:00:00.000 --> 00:00:01.000\nciao'),
    pause: vi.fn(() => Promise.resolve()),
    report: (status) => {
      statuses.push(status);
      return Promise.resolve();
    },
    fetch: (_input, init) => {
      sent = JSON.parse(typeof init?.body === 'string' ? init.body : '') as ImportLessonRequest;
      return Promise.resolve(Response.json(okResponse));
    },
    ...overrides,
  };
  return { deps: base, statuses, sent: () => sent };
}

describe('runImportJob', () => {
  it('aggiunge i sottotitoli e scarta il video senza riassunto né sottotitoli', async () => {
    const pause = vi.fn(() => Promise.resolve());
    const { deps: d, statuses, sent } = deps({ pause });
    const final = await runImportJob(preview, connection, d);
    expect(final).toMatchObject({
      phase: 'done',
      missingSubtitles: 1,
      lessonTitle: 'Binary trees',
    });
    expect(sent()?.parts.map((part) => part.epicodeId)).toEqual(['1']);
    expect(sent()?.parts[0]?.subtitles?.[0]?.cues).toEqual([
      { startMs: 0, endMs: 1000, text: 'ciao' },
    ]);
    expect(statuses.map((s) => s.phase)).toEqual(['subtitles', 'subtitles', 'sending', 'done']);
    expect(pause).toHaveBeenCalledTimes(1);
  });

  it('continua se una traccia non si scarica', async () => {
    const { deps: d, sent } = deps({ fetchText: () => Promise.reject(new Error('403')) });
    const final = await runImportJob(preview, connection, d);
    expect(final).toMatchObject({ phase: 'done', missingSubtitles: 2 });
    expect(sent()?.parts[0]?.subtitles).toBeUndefined();
  });

  it('riporta l’errore dell’API con il suo messaggio', async () => {
    const { deps: d } = deps({
      fetch: () =>
        Promise.resolve(
          Response.json(
            { error: { code: 'UNAUTHORIZED', message: 'Ricollega l’estensione' } },
            { status: 401 },
          ),
        ),
    });
    expect(await runImportJob(preview, connection, d)).toEqual({
      phase: 'error',
      message: 'Ricollega l’estensione',
      code: 'UNAUTHORIZED',
    });
  });

  it('con il limite orario attende e ritenta l’invio una volta, senza rileggere i video', async () => {
    let calls = 0;
    const loadTracks = vi.fn(() => Promise.resolve(null));
    const waitForRateLimit = vi.fn(() => Promise.resolve(true));
    const { deps: d } = deps({
      loadTracks,
      waitForRateLimit,
      fetch: () => {
        calls += 1;
        return Promise.resolve(
          calls === 1
            ? Response.json(
                { error: { code: 'RATE_LIMITED', message: 'Troppi import' } },
                { status: 429, headers: { 'retry-after': '120' } },
              )
            : Response.json(okResponse),
        );
      },
    });
    expect(await runImportJob(preview, connection, d)).toMatchObject({ phase: 'done' });
    expect(waitForRateLimit).toHaveBeenCalledWith(120);
    expect(loadTracks).toHaveBeenCalledTimes(2);
    expect(calls).toBe(2);
  });

  it('senza attesa per il limite orario mostra l’errore', async () => {
    const { deps: d } = deps({
      fetch: () =>
        Promise.resolve(
          Response.json(
            { error: { code: 'RATE_LIMITED', message: 'Troppi import' } },
            { status: 429 },
          ),
        ),
    });
    expect(await runImportJob(preview, connection, d)).toMatchObject({
      phase: 'error',
      code: 'RATE_LIMITED',
    });
  });

  it('usa la pausa tra i video indicata dal chiamante', async () => {
    const pause = vi.fn(() => Promise.resolve());
    const { deps: d } = deps({ pause, videoPauseMs: () => 4321 });
    await runImportJob(preview, connection, d);
    expect(pause).toHaveBeenCalledWith(4321);
  });

  it('segnala quando non resta nulla da importare', async () => {
    const { deps: d } = deps({ loadTracks: () => Promise.resolve(null) });
    const onlyEmpty = { ...preview, request: { ...request, parts: request.parts.slice(1, 2) } };
    expect(await runImportJob(onlyEmpty, connection, d)).toMatchObject({ phase: 'error' });
  });

  it('gestisce un server irraggiungibile', async () => {
    const { deps: d } = deps({ fetch: () => Promise.reject(new TypeError('offline')) });
    expect(await runImportJob(preview, connection, d)).toMatchObject({
      phase: 'error',
      message: expect.stringContaining('non è raggiungibile') as string,
    });
  });
});
