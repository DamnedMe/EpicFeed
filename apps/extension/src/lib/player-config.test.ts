import { describe, expect, it } from 'vitest';
import { extractPlayerConfig, tracksFromConfig } from './player-config';

// Forma della pagina del player osservata nel file HAR (valori inventati).
const page = `var x = 1;
window.playerConfig = {"video":{"id":123},"request":{"lang":"en","referrer":"https://learn.epicode.edu.mt/","text_tracks":[{"id":1,"lang":"en-x-autogen","url":"https://captions.vimeo.com/captions/1.vtt?expires=1\\u0026sig=a","kind":"captions","label":"English (auto-generated)","provenance":"ai_generated"},{"id":2,"lang":"it","url":"https://captions.vimeo.com/captions/2.vtt?expires=1\\u0026sig=b","kind":"subtitles","label":"Italiano {}","provenance":"user_uploaded","default":true}]}}; if (window.x) {}`;

describe('extractPlayerConfig', () => {
  it('isola l’oggetto anche con parentesi dentro le stringhe', () => {
    const config = extractPlayerConfig(page) as { video: { id: number } };
    expect(config.video.id).toBe(123);
  });

  it('restituisce null se la configurazione manca o è troncata', () => {
    expect(extractPlayerConfig('nulla qui')).toBeNull();
    expect(extractPlayerConfig('window.playerConfig = {"a": "b"')).toBeNull();
    expect(extractPlayerConfig('window.playerConfig = {a: 1}')).toBeNull();
  });
});

describe('tracksFromConfig', () => {
  it('elenca le tracce e riconosce quelle automatiche', () => {
    expect(tracksFromConfig(extractPlayerConfig(page))).toEqual([
      {
        language: 'en-x-autogen',
        url: expect.stringContaining('/1.vtt') as string,
        autoGenerated: true,
      },
      { language: 'it', url: expect.stringContaining('/2.vtt') as string, autoGenerated: false },
    ]);
  });

  it('scarta URL fuori da captions.vimeo.com e configurazioni sconosciute', () => {
    const evil = { request: { text_tracks: [{ lang: 'it', url: 'https://evil.test/x.vtt' }] } };
    expect(tracksFromConfig(evil)).toEqual([]);
    expect(tracksFromConfig(null)).toEqual([]);
  });
});

describe('tracksFromConfig con dati malformati', () => {
  it('ignora voci senza lingua o con URL non valido', () => {
    const config = {
      request: {
        text_tracks: [
          { lang: 'it' },
          { lang: 1, url: 'https://captions.vimeo.com/a.vtt' },
          { lang: 'it', url: '::' },
        ],
      },
    };
    expect(tracksFromConfig(config)).toEqual([]);
    expect(tracksFromConfig({ request: { text_tracks: 'x' } })).toEqual([]);
  });
});
