import type { ImportLessonRequest } from '@epicfeed/ingest';
import { ApiCallError, sendImport } from './api';
import type { Connection } from './connection';
import type { ImportStatus, LessonPreview } from './messages';
import type { PlayerTrack } from './player-config';
import { parseVtt } from './vtt';

/** Dipendenze del job di import (il service worker passa quelle reali). */
export interface ImportJobDeps {
  /** Carica il player nascosto del video e attende le tracce (o `null` se non arrivano). */
  loadTracks(videoId: string): Promise<PlayerTrack[] | null>;
  /** Scarica un file di sottotitoli. */
  fetchText(url: string): Promise<string>;
  /** Pausa tra un video e l'altro (traffico distribuito come un uso normale). */
  pause(ms: number): Promise<void>;
  /** Aggiorna lo stato mostrato dal popup. */
  report(status: ImportStatus): Promise<void>;
  fetch: typeof fetch;
  /** Durata della pausa tra due video (predefinita {@link PAUSE_BETWEEN_VIDEOS_MS}). */
  videoPauseMs?: () => number;
  /**
   * Chiamata quando EpicFeed risponde "troppi import": attende e dice se
   * riprovare. Senza, l'errore si mostra subito (import di una lezione).
   */
  waitForRateLimit?: (retryAfterSeconds: number) => Promise<boolean>;
}

/** Attesa predefinita se il server non indica `Retry-After`. */
const DEFAULT_RETRY_AFTER_S = 600;

/** Pausa tra la lettura di due video. */
export const PAUSE_BETWEEN_VIDEOS_MS = 1500;

/**
 * Esegue l'import di una lezione: legge i sottotitoli di ogni parte video,
 * uno alla volta, poi invia tutto a EpicFeed. Se un player non risponde o
 * una traccia non si scarica, la parte entra comunque con il solo riassunto.
 *
 * @param preview - Lezione letta dal portale.
 * @param connection - Collegamento con la web app.
 * @param deps - Dipendenze.
 * @returns Lo stato finale (anche già comunicato con `report`).
 */
export async function runImportJob(
  preview: LessonPreview,
  connection: Connection,
  deps: ImportJobDeps,
): Promise<ImportStatus> {
  const subtitles = new Map<
    string,
    NonNullable<ImportLessonRequest['parts'][number]['subtitles']>
  >();
  let missing = 0;

  for (const [index, video] of preview.videos.entries()) {
    await deps.report({ phase: 'subtitles', done: index, total: preview.videos.length });
    if (index > 0) await deps.pause(deps.videoPauseMs?.() ?? PAUSE_BETWEEN_VIDEOS_MS);
    const tracks = (await deps.loadTracks(video.videoId)) ?? [];
    const loaded = [];
    for (const track of tracks.slice(0, 4)) {
      try {
        const cues = parseVtt(await deps.fetchText(track.url)).slice(0, 10_000);
        if (cues.length > 0) {
          loaded.push({ language: track.language, autoGenerated: track.autoGenerated, cues });
        }
      } catch {
        // Traccia non disponibile: si prosegue con le altre.
      }
    }
    if (loaded.length === 0) missing += 1;
    else subtitles.set(video.partEpicodeId, loaded);
  }

  // Una parte video senza riassunto entra solo se ha i sottotitoli.
  const parts = preview.request.parts
    .map((part) => {
      const tracks = subtitles.get(part.epicodeId);
      return tracks ? { ...part, subtitles: tracks } : part;
    })
    .filter(
      (part) =>
        part.content.kind === 'reading' ||
        Object.keys(part.content.summaries).length > 0 ||
        (part.subtitles?.length ?? 0) > 0,
    );

  if (parts.length === 0) {
    const status: ImportStatus = {
      phase: 'error',
      message: 'Nessun contenuto da importare.',
      code: 'EMPTY',
    };
    await deps.report(status);
    return status;
  }

  for (let attempt = 0; ; attempt += 1) {
    await deps.report({ phase: 'sending' });
    try {
      const result = await sendImport(
        connection.apiBaseUrl,
        connection.token,
        { ...preview.request, parts },
        deps.fetch,
      );
      const status: ImportStatus = {
        phase: 'done',
        lessonTitle: preview.request.path.lesson.title,
        result,
        missingSubtitles: missing,
      };
      await deps.report(status);
      return status;
    } catch (error) {
      // Limite orario di EpicFeed: i sottotitoli sono già letti, quindi si
      // attende e si ritenta solo l'invio (una volta).
      if (
        error instanceof ApiCallError &&
        error.code === 'RATE_LIMITED' &&
        attempt === 0 &&
        deps.waitForRateLimit &&
        (await deps.waitForRateLimit(error.retryAfterSeconds ?? DEFAULT_RETRY_AFTER_S))
      ) {
        continue;
      }
      const status: ImportStatus = {
        phase: 'error',
        message: error instanceof Error ? error.message : 'Import non riuscito.',
        ...(error instanceof ApiCallError && error.code ? { code: error.code } : {}),
      };
      await deps.report(status);
      return status;
    }
  }
}
