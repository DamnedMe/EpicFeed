import { describe, expect, it, vi } from 'vitest';
import type { ContentVersionId, LessonPartId, LessonId } from '@epicfeed/shared';
import type {
  LessonForGeneration,
  LessonsToGenerateResult,
  SaveLessonFeedResult,
} from '@epicfeed/feed';
import { DomainError } from '@epicfeed/shared';
import { FeedValidationError, MAX_FEED_BODY_BYTES, MAX_SLIDES_BODY_BYTES } from '@epicfeed/feed';
import {
  accessDeps,
  bi,
  errorOf,
  lessonId,
  logError,
  partId,
  record,
  request,
  user,
} from '@/server/generation-test-kit';
import {
  handleImportSlides,
  handleListCatalog,
  handleListLessons,
  handleReadLesson,
  handleSaveFeed,
  type FeedGenerationDeps,
} from './generation-handler';

vi.mock('server-only', () => ({}));

const listResult: LessonsToGenerateResult = {
  lessons: [
    {
      lessonId: lessonId as LessonId,
      lessonTitle: 'Binary trees',
      chapterTitle: 'Trees',
      subjectTitle: 'DSA',
      partCount: 2,
    },
  ],
  totals: { lessons: 3, ready: 2, toGenerate: 1 },
};

const lesson = {
  lessonId,
  lessonTitle: 'Binary trees',
  chapterTitle: 'Trees',
  subjectId: '40000000-0000-4000-8000-000000000001',
  subjectTitle: 'DSA',
  sourcesHash: 'a'.repeat(64),
  parts: [
    {
      lessonPartId: partId,
      contentVersionId: '30000000-0000-4000-8000-000000000001',
      contentHash: 'b'.repeat(64),
      title: 'AVL',
      kind: 'video',
      position: 0,
      content: { kind: 'video', summaries: { it: 'Riassunto', en: 'Summary' } },
      generationStatus: 'generating',
      subtitles: [
        { language: 'it', autoGenerated: false, cues: [{ startMs: 0, endMs: 1, text: 'x' }] },
      ],
    },
  ],
  glossary: [],
} as unknown as LessonForGeneration;

const saveResult: SaveLessonFeedResult = {
  feedId: '50000000-0000-4000-8000-000000000001',
  created: true,
  cards: 3,
  alignedCards: 2,
};

const feed = {
  cards: [
    {
      id: 'avl',
      kind: 'concept',
      title: bi('Albero AVL', 'AVL tree'),
      keyPoint: bi('Un BST bilanciato.', 'A balanced BST.'),
      body: bi('Si ribilancia.', 'It rebalances.'),
      terms: [],
      conceptKeys: ['avl-tree'],
      sourcePartId: partId,
      origin: 'summary',
    },
  ],
  quiz: [],
  concepts: [{ key: 'avl-tree', name: bi('AVL', 'AVL'), description: bi('a', 'b') }],
  glossary: [],
};
const saveBody = { lessonId, sourcesHash: 'a'.repeat(64), promptVersion: '2026-11-21.1', feed };

function deps(overrides: Partial<FeedGenerationDeps> = {}): FeedGenerationDeps {
  return {
    ...accessDeps(),
    listLessons: () => Promise.resolve(listResult),
    readLesson: () => Promise.resolve(lesson),
    saveFeed: () => Promise.resolve(saveResult),
    listOwnedLessons: () =>
      Promise.resolve([
        {
          lessonId: lessonId as LessonId,
          lessonTitle: 'Binary trees',
          chapterTitle: 'Trees',
          subjectTitle: 'DSA',
          slides: 1,
        },
      ]),
    importSlides: (_user, _lesson, presentations) =>
      Promise.resolve(
        presentations.map((p) => ({
          number: p.number,
          lessonPartId: partId as LessonPartId,
          contentVersionId: '30000000-0000-4000-8000-000000000009' as ContentVersionId,
          newVersion: true,
          pages: p.content.pages.length,
        })),
      ),
    ...overrides,
  };
}

const post = (payload: unknown, headers: Record<string, string> = {}) =>
  request(`/api/generation/lessons/${lessonId}/feed`, {
    method: 'POST',
    headers,
    body: typeof payload === 'string' ? payload : JSON.stringify(payload),
  });

describe('GET /api/generation/lessons', () => {
  it('restituisce le lezioni da generare con il limite richiesto', async () => {
    const listLessons = vi.fn(() => Promise.resolve(listResult));
    const response = await handleListLessons(
      request('/api/generation/lessons?limit=5'),
      deps({ listLessons }),
    );
    expect(response.status).toBe(200);
    expect(await response.json()).toEqual(listResult);
    expect(listLessons).toHaveBeenCalledWith(user, 5);
  });

  it('usa 20 se il limite non è valido e gestisce gli errori inattesi', async () => {
    const listLessons = vi.fn(() => Promise.reject(new Error('db giù')));
    const response = await handleListLessons(
      request('/api/generation/lessons?limit=abc'),
      deps({ listLessons }),
    );
    expect(listLessons).toHaveBeenCalledWith(user, 20);
    expect(response.status).toBe(500);
    expect(logError).toHaveBeenCalled();
  });
});

describe('GET /api/generation/lessons/:id', () => {
  it('restituisce le fonti senza i sottotitoli e registra la lettura', async () => {
    const response = await handleReadLesson(request('/api/generation/lessons/x'), lessonId, deps());
    expect(response.status).toBe(200);
    const body = (await response.json()) as { parts: Record<string, unknown>[] };
    expect(body.parts[0]?.hasSubtitles).toBe(true);
    expect(body.parts[0]).not.toHaveProperty('subtitles');
    expect(body.parts[0]).not.toHaveProperty('contentVersionId');
    expect(record).toHaveBeenCalledWith(user, 'read', lessonId);
  });

  it('rifiuta un id non valido e una lezione non posseduta', async () => {
    expect((await handleReadLesson(request('/x'), 'non-uuid', deps())).status).toBe(400);
    const notFound = await handleReadLesson(
      request('/x'),
      lessonId,
      deps({ readLesson: () => Promise.reject(new DomainError('NOT_FOUND', 'x')) }),
    );
    expect(notFound.status).toBe(404);
  });
});

describe('POST /api/generation/lessons/:id/feed', () => {
  it('salva il feed e risponde 201, oppure 200 se esisteva già', async () => {
    const saveFeed = vi.fn(() => Promise.resolve(saveResult));
    const response = await handleSaveFeed(post(saveBody), lessonId, deps({ saveFeed }));
    expect(response.status).toBe(201);
    expect(await response.json()).toEqual(saveResult);
    expect(record).toHaveBeenCalledWith(user, 'save', lessonId);
    const again = await handleSaveFeed(
      post(saveBody),
      lessonId,
      deps({ saveFeed: () => Promise.resolve({ ...saveResult, created: false }) }),
    );
    expect(again.status).toBe(200);
  });

  it('elenca tutti i problemi di forma', async () => {
    const broken = {
      ...saveBody,
      feed: { ...feed, cards: [{ ...feed.cards[0], title: { it: 'x' } }] },
    };
    const response = await handleSaveFeed(post(broken), lessonId, deps());
    expect(response.status).toBe(422);
    const error = await errorOf(response);
    expect(error.code).toBe('INVALID_FEED');
    expect(error.issues?.[0]?.path).toBe('feed.cards.0.title.en');
  });

  it('restituisce i problemi delle regole del dominio', async () => {
    const response = await handleSaveFeed(
      post(saveBody),
      lessonId,
      deps({
        saveFeed: () =>
          Promise.reject(new FeedValidationError([{ path: 'quiz', message: 'Servono domande' }])),
      }),
    );
    expect(response.status).toBe(422);
    expect((await errorOf(response)).issues).toEqual([
      { path: 'quiz', message: 'Servono domande' },
    ]);
  });

  it('risponde 409 se le fonti sono cambiate e 422 per altri errori di dominio', async () => {
    const changed = await handleSaveFeed(
      post(saveBody),
      lessonId,
      deps({ saveFeed: () => Promise.reject(new DomainError('SOURCES_CHANGED', 'cambiata')) }),
    );
    expect(changed.status).toBe(409);
    const other = await handleSaveFeed(
      post(saveBody),
      lessonId,
      deps({ saveFeed: () => Promise.reject(new DomainError('INVALID_CONTENT', 'x')) }),
    );
    expect(other.status).toBe(422);
  });

  it('rifiuta JSON non valido, lezione diversa dal percorso, id non valido e corpi troppo grandi', async () => {
    expect((await handleSaveFeed(post('{'), lessonId, deps())).status).toBe(400);
    const otherLesson = { ...saveBody, lessonId: '10000000-0000-4000-8000-000000000009' };
    expect((await handleSaveFeed(post(otherLesson), lessonId, deps())).status).toBe(400);
    expect((await handleSaveFeed(post(saveBody), 'x', deps())).status).toBe(400);
    const declared = post(saveBody, { 'content-length': String(MAX_FEED_BODY_BYTES + 1) });
    expect((await handleSaveFeed(declared, lessonId, deps())).status).toBe(413);
    const huge = post('x'.repeat(MAX_FEED_BODY_BYTES + 10));
    expect((await handleSaveFeed(huge, lessonId, deps())).status).toBe(413);
  });
});

