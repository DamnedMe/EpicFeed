function deps(overrides: Partial<GenerationHandlerDeps> = {}): GenerationHandlerDeps {
  record.mockClear();
  logError.mockClear();
  return {
    verifyToken: (t) => Promise.resolve(t === token ? user : null),
    isAllowed: () => Promise.resolve(true),
    record,
    listLessons: () => Promise.resolve(listResult),
    readLesson: () => Promise.resolve(lesson),
    saveFeed: () => Promise.resolve(saveResult),
    listOwnedLessons: () =>
      Promise.resolve([
        {
          lessonId: lessonId as LessonId,
          lessonTitle: 'Binary trees',
          chapterTitle: 'Trees',
          subjectTitle: 'DSA',
          slides: 1,
        },
      ]),
    importSlides: (_user, _lesson, presentations) =>
      Promise.resolve(
        presentations.map((p) => ({
          number: p.number,
          lessonPartId: partId as LessonPartId,
          contentVersionId: '30000000-0000-4000-8000-000000000009' as ContentVersionId,
          newVersion: true,
          pages: p.content.pages.length,
        })),
      ),
    listExamLessons: () =>
      Promise.resolve({
        lessons: [
          {
            lessonId: lessonId as LessonId,
            lessonTitle: 'Binary trees',
            chapterTitle: 'Trees',
            subjectTitle: 'DSA',
          },
        ],
        totals: { lessons: 2, ready: 1, toGenerate: 1 },
      }),
    readLessonForExam: () => Promise.resolve(examMaterial),
    saveExamPack: () =>
      Promise.resolve({ packId: feedId, created: true, questions: 10, openQuestions: 1 }),
    listExamSubjects: () =>
      Promise.resolve([{ subjectId: lessonId, subjectTitle: 'DSA', concepts: [], hasBank: false }]),
    saveExamBank: () =>
      Promise.resolve({ bankId: feedId, created: true, officials: 1, variants: 2 }),
    logError,
    ...overrides,
  };
}

function request(path: string, init: RequestInit = {}, auth = token): Request {
  return new Request(`https://app.test${path}`, {
    ...init,
    headers: {
      authorization: `Bearer ${auth}`,
      'content-type': 'application/json',
      ...(init.headers as Record<string, string> | undefined),
    },
  });
}

const post = (payload: unknown, headers: Record<string, string> = {}) =>
  request(`/api/generation/lessons/${lessonId}/feed`, {
    method: 'POST',
    headers,
    body: typeof payload === 'string' ? payload : JSON.stringify(payload),
  });

async function errorOf(response: Response) {
  return ((await response.json()) as { error: { code: string; issues?: { path: string }[] } })
    .error;
}

